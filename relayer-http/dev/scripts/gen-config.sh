#!/usr/bin/env bash
# Writes dev/config/kms-<N>.yaml for a stack of N KMS connectors with MPC threshold t:
# user decrypt needs 2t+1 shares, public decrypt t+1 identical answers. Usage: gen-config.sh N T ["scenario note"]
set -euo pipefail
N="${1:?number of KMS connectors}"
T="${2:?MPC threshold t (0 for the centralized single node)}"
NOTE="${3:-}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/config/kms-$N.yaml"
USER_THR=$((2 * T + 1)); PUBLIC_THR=$((T + 1))
{
  cat <<HDR
# Local stack with $N KMS connector(s), MPC threshold t=$T${NOTE:+: $NOTE}.
# user decrypt needs $USER_THR shares, public decrypt $PUBLIC_THR identical answers. Generated by
# dev/scripts/gen-config.sh $N $T. Each 127.0.0.1:808x is a forwarder to one connector proxy (dev/scripts/proxies-up.sh);
# the proxy checks the Bearer key from KMS_API_KEY.
name: relayer-http-dev
log:
  format: pretty
  show_file_line: false
  show_thread_ids: false
  show_timestamp: true
  show_target: false
http:
  endpoint: "0.0.0.0:8080"
  max_body_bytes: 2097152
  supported_chain_ids: [12345, 67890]   # the two local host chains
kms_aggregator:
  allow_insecure_http: false            # loopback http is allowed as is
  max_concurrent_calls: 16
  call:
    timeout: 60s                        # local decrypts are slow; 60s is the configured maximum
    retries:
      max_retries: 0
      delay: 500ms
      backoff_max: 4s
  public_decrypt:
    threshold: $PUBLIC_THR
  user_decrypt:
    threshold: $USER_THR
  endpoints:
HDR
  for i in $(seq 1 "$N"); do
    echo "    - { name: kms_$i, url: \"http://127.0.0.1:808$i\", auth: { type: api_key, value_env: KMS_API_KEY } }"
  done
} > "$OUT"
echo "wrote $OUT (endpoints=$N, user threshold=$USER_THR, public threshold=$PUBLIC_THR)"
