//! The normative Connector-authorization vector set: generator and runner in one place.
//!
//! The set is owned by this file and committed as JSON next to the schema every other
//! implementation includes. Generation and checking share one code path — the tests build the set
//! in memory and compare it against the committed file, and the same build is written to disk when
//! the update gate is set:
//!
//! ```text
//! bash solana/scripts/update-connector-auth-vectors.sh
//! ```
//!
//! There is no separate generator binary, for the reason PR1 recorded: a generator that is not the
//! runner drifts from it, and then the committed file agrees with neither.
//!
//! ## What this set is for, and what it is not for
//!
//! Every record here is also covered by a Rust test in this suite, so for this implementation the
//! set adds review value rather than pinning value: it is generated by the same builders the tests
//! use. What it does add is a statement of the host policy that can be read, reviewed and consumed
//! outside Rust — the SDK can check its pre-checks against the window, scope, budget and
//! deployment records, and a future host implementation has a table of expected outcomes to
//! converge on rather than a suite to reimplement.
//!
//! Two disciplines are enforced on the set itself:
//!
//! * a rejecting record is derived from an accepted one by exactly one documented mutation, and the
//!   runner checks that the base is authorized — so "this request is rejected" cannot be passing
//!   for an unrelated reason;
//! * every rule in the dictionary is exercised by some record, and every rule some record declares
//!   is one the Connector actually produces. Both directions, or a regeneration could quietly drop
//!   a class.

