/// The committed file is the build. Under the update gate it is rewritten from it instead — the
/// generator and the runner are one code path, so the file cannot agree with neither.
#[test]
fn committed_vectors_match_the_generator() {
    let built = build_file();
    let serialized = serde_json::to_string_pretty(&built).expect("the set serializes") + "\n";

    if std::env::var(UPDATE_ENV).is_ok() {
        std::fs::write(vector_path(), &serialized).expect("the set is written");
        return;
    }

    let committed = committed_file();
    assert_eq!(
        committed, built,
        "the committed set and the generated set differ; regenerate with \
         `bash solana/scripts/update-connector-auth-vectors.sh`"
    );
}

/// Every record behaves as declared, replayed from the file.
#[tokio::test]
async fn every_vector_behaves_as_declared() {
    let file = committed_file();

    for record in &file.vectors {
        let outcome = replay(record, &file).await;
        match record.result {
            VectorResult::Valid | VectorResult::Acceptable => assert_eq!(
                outcome,
                Outcome::Authorized,
                "record '{}' is declared {:?} but was rejected",
                record.name,
                record.result
            ),
            VectorResult::Invalid => {
                let declared_rule = record
                    .rule
                    .as_deref()
                    .expect("a rejecting record names a rule");
                let declared_class = record.class.expect("a rejecting record names a class");
                assert_eq!(
                    outcome,
                    Outcome::Rejected(
                        rule::ALL
                            .iter()
                            .copied()
                            .find(|name| *name == declared_rule)
                            .unwrap_or_else(|| panic!(
                                "record '{}' names rule '{declared_rule}', which is not in the \
                                 dictionary",
                                record.name
                            )),
                        declared_class
                    ),
                    "record '{}' must be rejected by '{declared_rule}' as {declared_class:?}",
                    record.name
                );
            }
        }
    }
}

/// A rejecting record's base must be authorized. Without this, "the request is rejected" could be
/// true for a reason unrelated to the mutation the record describes.
#[tokio::test]
async fn the_base_of_every_rejecting_record_is_authorized() {
    let file = committed_file();

    for record in &file.vectors {
        let Some(base_name) = record.derived_from.as_deref() else {
            continue;
        };
        let base = file
            .vectors
            .iter()
            .find(|candidate| candidate.name == base_name)
            .unwrap_or_else(|| {
                panic!(
                    "record '{}' derives from '{base_name}', which is not in the set",
                    record.name
                )
            });
        assert!(
            matches!(base.result, VectorResult::Valid | VectorResult::Acceptable),
            "record '{}' derives from '{base_name}', which is not an accepted record",
            record.name
        );
        assert_eq!(
            replay(base, &file).await,
            Outcome::Authorized,
            "record '{}' derives from '{base_name}', which is not authorized — so its rejection \
             says nothing about the mutation",
            record.name
        );
    }
}

/// Every rule is exercised, and every rule the set declares is one the dictionary names. Both
/// directions: a regeneration that dropped a class would otherwise pass.
#[test]
fn the_set_covers_the_rule_dictionary_in_both_directions() {
    let file = committed_file();
    let declared: BTreeSet<&str> = file
        .vectors
        .iter()
        .filter_map(|record| record.rule.as_deref())
        .collect();
    let dictionary: BTreeSet<&str> = rule::ALL.iter().copied().collect();

    let uncovered: Vec<&&str> = dictionary.difference(&declared).collect();
    assert!(
        uncovered.is_empty(),
        "these rules are in the dictionary but no record exercises them: {uncovered:?}"
    );
    let unknown: Vec<&&str> = declared.difference(&dictionary).collect();
    assert!(
        unknown.is_empty(),
        "these rules are declared by records but are not in the dictionary: {unknown:?}"
    );
}

/// Structural requirements on the records themselves.
#[test]
fn records_carry_the_required_fields() {
    let file = committed_file();
    let mut names = BTreeSet::new();

    for record in &file.vectors {
        assert!(
            names.insert(record.name.clone()),
            "record name '{}' appears twice",
            record.name
        );
        assert!(
            !record.comment.trim().is_empty(),
            "record '{}' has no comment, and a record whose purpose is not written down is a record \
             nobody can review",
            record.name
        );
        match record.result {
            VectorResult::Invalid => {
                assert!(
                    record.rule.is_some(),
                    "record '{}' rejects without a rule",
                    record.name
                );
                assert!(
                    record.class.is_some(),
                    "record '{}' rejects without a class",
                    record.name
                );
                assert!(
                    record.derived_from.is_some() && record.mutation.is_some(),
                    "record '{}' rejects without naming its base and its mutation",
                    record.name
                );
            }
            VectorResult::Valid | VectorResult::Acceptable => {
                assert!(
                    record.rule.is_none() && record.class.is_none(),
                    "record '{}' is accepted and must name no rule",
                    record.name
                );
            }
        }
        assert!(
            !record.observation.accounts.is_empty()
                || record.name == "missing-encrypted-value-account",
            "record '{}' carries no accounts, which is only meaningful for an absence case",
            record.name
        );
    }
}

