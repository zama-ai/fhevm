fn record_of(scenario: &Scenario) -> ConnectorAuthVector {
    let permit = &scenario.request.permit;
    ConnectorAuthVector {
        name: scenario.name.to_owned(),
        comment: scenario.comment.to_owned(),
        result: scenario.result,
        rule: scenario.rule.map(str::to_owned),
        class: scenario.class,
        derived_from: scenario.derived_from.map(str::to_owned),
        mutation: scenario.mutation.map(str::to_owned),
        request: WireRequest {
            permit: WirePermit {
                user_pubkey: to_hex(&permit.user_pubkey),
                transport_key: TRANSPORT_KEY_NAME.to_owned(),
                allowed_acl_domain_keys: permit
                    .allowed_acl_domain_keys
                    .iter()
                    .map(|key| to_hex(key))
                    .collect(),
                start_timestamp: permit.start_timestamp.to_string(),
                duration_seconds: permit.duration_seconds.to_string(),
                verifying_program_id: to_hex(&permit.verifying_program_id),
                chain_id: permit.chain_id.to_string(),
                extra_data: to_hex(&permit.extra_data),
            },
            signature: to_hex(&scenario.request.signature),
            handles: scenario
                .request
                .handles
                .iter()
                .map(|entry| WireHandleEntry {
                    handle: to_hex(&entry.handle),
                    subject: to_hex(&entry.subject),
                    encrypted_value_id: to_hex(&entry.encrypted_value_id),
                    proof_leaf_count: entry.proof_leaf_count.to_string(),
                    access_proof: to_hex(&entry.access_proof),
                })
                .collect(),
            // The canonical bytes of the same request: what the gateway event carries
            // opaquely. Recorded from the canonical encoder so every consumer of this set
            // can verify its own codec in both directions against the typed fields above.
            solana_request: to_hex(
                &encode_solana_request(&scenario.request).expect("the scenario request serializes"),
            ),
        },
        observation: Observation {
            observed_slot: scenario.world.slot.to_string(),
            now_unix_seconds: scenario.now.to_string(),
            kms_pair_status: scenario.kms_pair_status,
            accounts: scenario
                .world
                .accounts()
                .map(|(key, account)| RecordedAccount {
                    pubkey: to_hex(key),
                    owner: to_hex(&account.owner),
                    data: to_hex(&account.data),
                })
                .collect(),
        },
    }
}

fn build_file() -> ConnectorAuthVectorFile {
    let scenarios = scenarios();
    let transport_key = scenarios
        .first()
        .map(|scenario| scenario.request.permit.transport_key.clone())
        .expect("the set is not empty");
    for scenario in &scenarios {
        assert_eq!(
            scenario.request.permit.transport_key, transport_key,
            "record '{}' uses a second transport key; the table would need another entry",
            scenario.name
        );
    }

    ConnectorAuthVectorFile {
        schema: CONNECTOR_AUTH_VECTOR_SCHEMA.to_owned(),
        description: "Connector-layer authorization vectors for Solana user decryption: the host \
                      policy applied to a request against a recorded observation of host state."
            .to_owned(),
        regenerate_with: "bash solana/scripts/update-connector-auth-vectors.sh".to_owned(),
        deployment: Deployment {
            verifying_program_id: to_hex(&PROGRAM_ID),
            genesis_hash: to_hex(&GENESIS_HASH),
            chain_id_decimal: CHAIN_ID.to_string(),
            chain_id_hex: format!("{CHAIN_ID:#018x}"),
            chain_id_be_bytes: to_hex(&CHAIN_ID.to_be_bytes()),
            chain_id_derivation: "deployment-time rule: chain_id = 0x8000000000000000 | \
                                  (be_u64(SHA-256(\"zama-solana-chain-id-v1\" || genesis_hash)[0..8]) \
                                  & 0x7fffffffffffffff), applied once per cluster and configured \
                                  everywhere. Nothing in the authorization path recomputes it, so \
                                  this set's pair is a synthetic cluster: the chain id below is not \
                                  the rule applied to the genesis hash below, and no check reads \
                                  the genesis hash at all. Vectors for the rule itself live with \
                                  the permit fixtures."
                .to_owned(),
        },
        transport_keys: BTreeMap::from([(TRANSPORT_KEY_NAME.to_owned(), to_hex(&transport_key))]),
        vectors: scenarios.iter().map(record_of).collect(),
    }
}

/// A validator that answers with whatever the record declares.
struct DeclaredKmsPair(KmsPairStatus);

impl KmsPairValidator for DeclaredKmsPair {
    async fn validate_pair(
        &self,
        _kms_context_id: &SolanaPubkeyBytes,
        _kms_epoch_id: &SolanaPubkeyBytes,
    ) -> Result<(), KmsPairFailure> {
        match self.0 {
            KmsPairStatus::Servable => Ok(()),
            KmsPairStatus::ContextUnknown => Err(KmsPairFailure::ContextUnknown),
            KmsPairStatus::ContextDestroyed => Err(KmsPairFailure::ContextDestroyed),
            // A record describes the management state; the Connector learns about all three of
            // these from one boolean and cannot tell which applies. The collapse belongs here, in
            // the adapter, rather than in the record — the world is more precise than the view of
            // it, and the set says so by keeping both.
            KmsPairStatus::EpochNotYetActive
            | KmsPairStatus::EpochOfAnotherContext
            | KmsPairStatus::EpochDestroyed => Err(KmsPairFailure::PairNotServable),
        }
    }
}

/// What the Connector made of a record.
#[derive(Debug, PartialEq, Eq)]
enum Outcome {
    Authorized,
    Rejected(&'static str, FailureClass),
}

/// The Connector's mapping from its own failure onto this set's rule names and classes.
///
/// Panics for failures this set does not cover, rather than inventing a name for them: the permit
/// layer has its own set, and a snapshot divergence cannot arise from a record that carries one
/// observation.
fn rule_name(failure: &AuthorizationFailure) -> &'static str {
    match failure {
        AuthorizationFailure::Form(form) => match form {
            RequestFormError::EmptyHandles => rule::EMPTY_HANDLES,
            RequestFormError::TooManyHandles { .. } => rule::TOO_MANY_HANDLES,
            RequestFormError::AccessProofMalformed { .. } => rule::ACCESS_PROOF_MALFORMED,
            RequestFormError::AccessProofTrailingBytes { .. } => rule::ACCESS_PROOF_TRAILING_BYTES,
            RequestFormError::AccessProofTooManySiblings { .. } => {
                rule::ACCESS_PROOF_TOO_MANY_SIBLINGS
            }
            RequestFormError::Permit(_)
            | RequestFormError::SignatureWidth { .. }
            | RequestFormError::EntryIdentityWidth { .. } => {
                panic!("the permit set covers this layer: {form}")
            }
        },
        AuthorizationFailure::SignatureMismatch | AuthorizationFailure::UnusableUserPubkey => {
            panic!("the permit set covers the signature rule")
        }
        AuthorizationFailure::Deployment(deployment) => match deployment {
            DeploymentFailure::ProgramIdMismatch { .. } => rule::DEPLOYMENT_PROGRAM_MISMATCH,
            DeploymentFailure::ChainIdMismatch { .. } => rule::DEPLOYMENT_CHAIN_ID_MISMATCH,
            DeploymentFailure::MixedEmbeddedChainIds { .. } => rule::MIXED_EMBEDDED_CHAIN_IDS,
            DeploymentFailure::EmbeddedChainIdMismatch { .. } => rule::EMBEDDED_CHAIN_ID_MISMATCH,
        },
        AuthorizationFailure::Window(window) => match window {
            WindowFailure::NotYetValid { .. } => rule::WINDOW_NOT_YET_VALID,
            WindowFailure::Expired { .. } => rule::WINDOW_EXPIRED,
        },
        AuthorizationFailure::Watermark(watermark) => match watermark {
            WatermarkFailure::Invalidated { .. } => rule::PERMIT_INVALIDATED,
            WatermarkFailure::NotAnInvalidationRecord { .. }
            | WatermarkFailure::RecordNamesAnotherUser { .. }
            | WatermarkFailure::ForeignOwner { .. } => rule::WATERMARK_RECORD_INVALID,
            WatermarkFailure::Snapshot(_) => panic!("a record carries one observation"),
        },
        AuthorizationFailure::KmsPair(_) => rule::KMS_PAIR_UNSERVABLE,
        AuthorizationFailure::Snapshot(_) => panic!("a record carries one observation"),
        AuthorizationFailure::EncryptedValueAccount { source, .. } => match source {
            EncryptedValueAccountFailure::Absent { .. } => rule::ENCRYPTED_VALUE_ACCOUNT_ABSENT,
            EncryptedValueAccountFailure::ForeignOwner { .. } => {
                rule::ENCRYPTED_VALUE_ACCOUNT_FOREIGN_OWNER
            }
            EncryptedValueAccountFailure::WrongAccountType { .. } => {
                rule::ENCRYPTED_VALUE_ACCOUNT_WRONG_TYPE
            }
            EncryptedValueAccountFailure::Malformed { .. } => {
                rule::ENCRYPTED_VALUE_ACCOUNT_MALFORMED
            }
            EncryptedValueAccountFailure::EncryptedValueIdMismatch { .. } => {
                rule::ENCRYPTED_VALUE_ID_MISMATCH
            }
            EncryptedValueAccountFailure::Snapshot(_) => panic!("a record carries one observation"),
        },
        AuthorizationFailure::HandleBinding { source, .. } => match source {
            HandleBindingFailure::NotCurrentHandle { .. } => rule::HANDLE_NOT_CURRENT,
            HandleBindingFailure::NotAMember { .. } => rule::SUBJECT_NOT_A_MEMBER,
            // Both proof outcomes reach a client through `InclusionFailed` below, which is where
            // they are classified by the claimed leaf count. Seeing one here would mean the
            // pipeline stopped folding them and the set lost that classification.
            HandleBindingFailure::LeafIndexOutOfRange { .. }
            | HandleBindingFailure::ProofDoesNotVerify { .. } => panic!(
                "an inclusion failure must arrive classified, not as a bare handle-binding failure"
            ),
            HandleBindingFailure::MmrStateInconsistent => {
                panic!("internally inconsistent host state is not a class of this set")
            }
        },
        AuthorizationFailure::InclusionFailed { .. } => rule::INCLUSION_PROOF_DOES_NOT_VERIFY,
        AuthorizationFailure::Scope { .. } => rule::DOMAIN_NOT_ALLOWED,
        AuthorizationFailure::Delegation { source, .. } => match source {
            DelegationFailure::Absent { .. } => rule::DELEGATION_ABSENT,
            DelegationFailure::Revoked => rule::DELEGATION_REVOKED,
            DelegationFailure::Expired { .. } => rule::DELEGATION_EXPIRED,
            DelegationFailure::NewerThanObservation { .. } => {
                rule::DELEGATION_NEWER_THAN_OBSERVATION
            }
            DelegationFailure::TupleMismatch { .. } => rule::DELEGATION_TUPLE_MISMATCH,
            DelegationFailure::ForeignOwner { .. } => rule::DELEGATION_FOREIGN_OWNER,
            DelegationFailure::NotADelegationRecord { .. } => rule::DELEGATION_WRONG_ACCOUNT_TYPE,
            DelegationFailure::NoLiveGrant { .. } => rule::DELEGATION_NO_LIVE_GRANT,
            DelegationFailure::Snapshot(_) => panic!("a record carries one observation"),
        },
    }
}

fn class_name(class: ConnectorClass) -> FailureClass {
    match class {
        ConnectorClass::Terminal => FailureClass::Terminal,
        ConnectorClass::Transient => FailureClass::Transient,
        ConnectorClass::Retryable => FailureClass::Retryable,
    }
}

/// Rebuilds a record's inputs and authorizes it — from the record, not from the scenario that
/// produced it, so what is under test is what the file says.
async fn replay(record: &ConnectorAuthVector, file: &ConnectorAuthVectorFile) -> Outcome {
    let permit = &record.request.permit;
    let wire = SolanaUserDecryptRequestWire {
        permit: PermitWireFields {
            user_pubkey: from_hex(&permit.user_pubkey).expect("hex"),
            transport_key: record
                .transport_key_bytes(file)
                .expect("the record names a key in the table"),
            allowed_acl_domain_keys: permit
                .allowed_acl_domain_keys
                .iter()
                .map(|key| from_hex(key).expect("hex"))
                .collect(),
            start_timestamp: permit.start_timestamp.parse().expect("decimal"),
            duration_seconds: permit.duration_seconds.parse().expect("decimal"),
            verifying_program_id: from_hex(&permit.verifying_program_id).expect("hex"),
            chain_id: permit.chain_id.parse().expect("decimal"),
            extra_data: from_hex(&permit.extra_data).expect("hex"),
        },
        signature: from_hex(&record.request.signature).expect("hex"),
        handles: record
            .request
            .handles
            .iter()
            .map(|entry| SolanaHandleEntryWire {
                handle: from_hex(&entry.handle).expect("hex"),
                subject: from_hex(&entry.subject).expect("hex"),
                encrypted_value_id: from_hex(&entry.encrypted_value_id).expect("hex"),
                proof_leaf_count: entry.proof_leaf_count.parse().expect("decimal"),
                access_proof: from_hex(&entry.access_proof).expect("hex"),
            })
            .collect(),
    };

    // The record's canonical bytes and its typed fields must be the same request under the
    // canonical codec, in both directions — this is what freezes the layout for every
    // implementation that consumes this set.
    let recorded_request = from_hex(&record.request.solana_request).expect("hex");
    assert_eq!(
        encode_solana_request(&wire).expect("the typed fields serialize"),
        recorded_request,
        "record {}: the typed fields do not encode to the recorded bytes",
        record.name
    );
    assert_eq!(
        decode_solana_request(&recorded_request).expect("the recorded bytes decode"),
        wire,
        "record {}: the recorded bytes do not decode to the typed fields",
        record.name
    );

    let world = World::from_accounts(
        record.observation.observed_slot.parse().expect("decimal"),
        record.observation.accounts.iter().map(|account| {
            let key: SolanaPubkeyBytes = from_hex(&account.pubkey)
                .expect("hex")
                .try_into()
                .expect("a 32-byte address");
            (
                key,
                SnapshotAccount {
                    owner: from_hex(&account.owner)
                        .expect("hex")
                        .try_into()
                        .expect("a 32-byte owner"),
                    data: from_hex(&account.data).expect("hex"),
                },
            )
        }),
    );

    let request = match SolanaUserDecryptRequest::decode(&wire) {
        Ok(request) => request,
        Err(form) => {
            let failure = AuthorizationFailure::Form(form);
            return Outcome::Rejected(rule_name(&failure), class_name(failure.class()));
        }
    };
    let reader = ScriptedReader::scripted(vec![world.clone(), world]);
    let deployment = deployment();
    let context = AuthorizationContext {
        deployment: &deployment,
        now_unix_seconds: record
            .observation
            .now_unix_seconds
            .parse()
            .expect("decimal"),
        // The vectors predate the gateway's typed declaration and do not probe it: every record
        // is replayed with the honest declaration (the signed list's actual length), so the
        // declaration rule never decides a vector's outcome.
    };
    match authorize_request(
        &reader,
        &DeclaredKmsPair(record.observation.kms_pair_status),
        context,
        &request,
    )
    .await
    {
        Ok(_) => Outcome::Authorized,
        Err(failure) => Outcome::Rejected(rule_name(&failure), class_name(failure.class())),
    }
}

