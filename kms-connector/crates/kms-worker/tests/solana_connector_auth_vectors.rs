// ---------------------------------------------------------------------------
// A scenario: a request, the state it is authorized against, and the expected outcome
// ---------------------------------------------------------------------------

struct Scenario {
    name: &'static str,
    comment: &'static str,
    result: VectorResult,
    rule: Option<&'static str>,
    class: Option<FailureClass>,
    derived_from: Option<&'static str>,
    mutation: Option<&'static str>,
    request: SolanaUserDecryptRequestWire,
    world: World,
    now: u64,
    kms_pair_status: KmsPairStatus,
}

impl Scenario {
    /// An accepted record.
    fn accepted(
        name: &'static str,
        comment: &'static str,
        request: SolanaUserDecryptRequestWire,
        world: World,
    ) -> Self {
        Self {
            name,
            comment,
            result: VectorResult::Valid,
            rule: None,
            class: None,
            derived_from: None,
            mutation: None,
            request,
            world,
            now: NOW_INSIDE_WINDOW,
            kms_pair_status: KmsPairStatus::Servable,
        }
    }

    /// A rejecting record, derived from an accepted one by one mutation.
    ///
    /// Eight arguments, deliberately: name, comment, base, mutation, rule, class, request, state
    /// are exactly what a record is, and grouping some of them into a struct would move the
    /// argument list into the call site without making it shorter. The same suppression is used by
    /// the permit crate for the same reason.
    #[allow(clippy::too_many_arguments)]
    fn rejected(
        name: &'static str,
        comment: &'static str,
        derived_from: &'static str,
        mutation: &'static str,
        rule: &'static str,
        class: FailureClass,
        request: SolanaUserDecryptRequestWire,
        world: World,
    ) -> Self {
        Self {
            name,
            comment,
            result: VectorResult::Invalid,
            rule: Some(rule),
            class: Some(class),
            derived_from: Some(derived_from),
            mutation: Some(mutation),
            request,
            world,
            now: NOW_INSIDE_WINDOW,
            kms_pair_status: KmsPairStatus::Servable,
        }
    }

    fn at_time(mut self, now: u64) -> Self {
        self.now = now;
        self
    }

    fn with_kms_status(mut self, status: KmsPairStatus) -> Self {
        self.kms_pair_status = status;
        self
    }

    fn recorded_as_acceptable(mut self, comment: &'static str) -> Self {
        self.result = VectorResult::Acceptable;
        self.comment = comment;
        self
    }
}

