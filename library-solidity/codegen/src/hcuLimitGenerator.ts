import type { FheTypeInfo, NBucketedCost, Price, PriceData } from './common';

// A cost row is two words: 64 bits per priced type, work in the high 32 bits and latency in the low 32 bits.
const SLOTS_PER_ROW = 8;
const SLOT_BITS = 64n;
const MAX_PRICE = 2 ** 32 - 1;

export function generateSolidityHCULimitOperators(priceData: PriceData, fheTypes: FheTypeInfo[]): string {
  if (!priceData) {
    throw new Error('undefined or null priceData');
  }

  checkPrices(priceData);
  const slots = costSlots(priceData, fheTypes);

  let output = `// SPDX-License-Identifier: BSD-3-Clause-Clear
  pragma solidity ^0.8.24;

  import {fhevmExecutorAdd} from "../addresses/FHEVMHostAddresses.sol";
  import {FheType} from "./shared/FheType.sol";

  /**
   * @title HCULimitOperators
   * @notice One entry point per FHE operator, with its prices, called by FHEVMExecutor. HCULimit inherits it and
   *         meters each operation in the functions declared at the end.
   * @dev Generated by library-solidity/codegen from the price file: change the prices or the generator, not this file.
   *      An operation's cost holds two prices in HCU: its work in the high 32 bits, charged to quotas, the capacity
   *      and the transaction limit, and its latency in the low 32 bits, added to depths.
   */
  abstract contract HCULimitOperators {
    /// @notice Returned if the sender is not the FHEVMExecutor.
    error CallerMustBeFHEVMExecutorContract();

    /// @notice Returned if the operation is not supported.
    error UnsupportedOperation();

    /// @notice Returned if the operation is not scalar.
    error OnlyScalarOperationsAreSupported();

    /// @notice FHEVMExecutor address.
    address internal constant FHEVM_EXECUTOR_ADDRESS = fhevmExecutorAdd;

    /// \`fheMulDiv\` \`scalarByte\` bitmask: bit 0 (divisor) is always set; bit 1 marks \`factor2\` as scalar.
    bytes1 private constant FHE_MUL_DIV_FACTOR2_ENCRYPTED = 0x01;
    bytes1 private constant FHE_MUL_DIV_FACTOR2_SCALAR = 0x03;

    /// @dev Slot of each FheType in a cost row, 4 bits per FheType value: 0 for a type without prices, else 1 to 8.
    ///      ${slots.legend}.
    uint256 private constant COST_SLOTS = ${hex256(slots.word)};

    /// @dev Returns \`fheType\`'s cost from a row of two words, 64 bits per slot. Reverts for a type without a slot,
    ///      types from 64 on included (the shift leaves 0), and for a slot without a price.
    function _cost(uint256 row0, uint256 row1, FheType fheType) private pure returns (uint256 cost) {
        uint256 slot = (COST_SLOTS >> (uint256(uint8(fheType)) * 4)) & 0xF;
        if (slot == 0) revert UnsupportedOperation();
        slot -= 1;
        cost = ((slot < 4 ? row0 : row1) >> ((slot % 4) * 64)) & type(uint64).max;
        if (cost == 0) revert UnsupportedOperation();
    }

\n\n`;
  for (const [operation, data] of Object.entries(priceData)) {
    const functionName = `checkHCUFor${operation.charAt(0).toUpperCase() + operation.slice(1)}`;
    const lhsName = operation === 'fheMulDiv' ? 'factor1' : 'lhs';
    const rhsName = operation === 'fheMulDiv' ? 'factor2' : 'rhs';
    const lhsDoc = operation === 'fheMulDiv' ? 'The first multiplication factor.' : 'The left-hand side operand.';
    const rhsDoc = operation === 'fheMulDiv' ? 'The second multiplication factor.' : 'The right-hand side operand.';

    output += generateCostRows(operation, data, slots);

    if (data.supportScalar && data.scalar && data.nonScalar) {
      switch (data.numberInputs) {
        case 1:
          output += `
        /**
        * @notice Check the homomorphic complexity units limit required for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
        * @param resultType Result type.
        * @param scalarByte Scalar byte.
        * @param ct The only operand.
        * @param result Result.
        * @param caller Original caller address from FHEVMExecutor.
         */
         function ${functionName}(FheType resultType, bytes1 scalarByte, bytes32 ct, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
    `;
          break;
        case 2:
          output += `
        /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param resultType Result type.
         * @param scalarByte Scalar byte.
         * @param ${lhsName} ${lhsDoc}
         * @param ${rhsName} ${rhsDoc}
         * @param result Result.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
         function ${functionName}(FheType resultType, bytes1 scalarByte, bytes32 ${lhsName}, bytes32 ${rhsName}, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
    `;
          break;
        default:
          throw new Error('Number of inputs for scalar and non-scalar must be less than 3');
      }
    } else if (data.supportScalar && data.scalar && !data.nonScalar) {
      switch (data.numberInputs) {
        case 2:
          output += `
        /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param resultType Result type.
         * @param scalarByte Scalar byte.
         * @param lhs The left-hand side operand.
         * @param result Result.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
         function ${functionName}(FheType resultType, bytes1 scalarByte, bytes32 lhs, bytes32 /*rhs*/, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
           `;
          break;
        default:
          throw new Error('Number of inputs for scalar with only scalar must be 2');
      }
    } else {
      switch (data.numberInputs) {
        case 0:
          output += `    /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param resultType Result type.
         * @param result Result.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
        function ${functionName}(FheType resultType, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
    `;
          break;
        case 1:
          output += `
      /**
        * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
        * @param ct The only operand.
        * @param result Result.
        * @param caller Original caller address from FHEVMExecutor.
        */
        function ${functionName}(FheType resultType, bytes32 ct, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
    `;
          break;
        case 2:
          output += `
        /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param resultType Result type.
         * @param lhs The left-hand side operand.
         * @param rhs The right-hand side operand.
         * @param result Result.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
        function ${functionName}(FheType resultType, bytes32 lhs, bytes32 rhs, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
    `;
          break;
        case 3:
          output += `
        /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param resultType Result type.
         * @param lhs The left-hand side operand.
         * @param middle The middle operand.
         * @param rhs The right-hand side operand.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
        function ${functionName}(FheType resultType, bytes32 lhs, bytes32 middle, bytes32 rhs, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 opCost;
    `;
          break;
        case -1:
          output += `
        /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param resultType Result type.
         * @param values Input ciphertext handles.
         * @param result Result handle.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
        function ${functionName}(FheType resultType, bytes32[] calldata values, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 n = values.length;
        uint256 opCost;
    `;
          break;
        case -2:
          output += `
        /**
         * @notice Check the homomorphic complexity units limit for ${operation.charAt(0).toUpperCase() + operation.slice(1)}.
         * @param valueType Value type.
         * @param value Input ciphertext handle.
         * @param values Encrypted set ciphertext handles.
         * @param result Result handle.
         * @param caller Original dapp caller address from FHEVMExecutor.
         */
        function ${functionName}(FheType valueType, bytes32 value, bytes32[] calldata values, bytes32 result, address caller) external virtual {
        if(msg.sender != FHEVM_EXECUTOR_ADDRESS) revert CallerMustBeFHEVMExecutorContract();
        uint256 n = values.length;
        uint256 opCost;
    `;
          break;
        default:
          throw new Error('Number of inputs must be less than 4');
      }
    }

    if (data.scalar && data.nonScalar) {
      if (operation === 'fheMulDiv') {
        output += `if (scalarByte == FHE_MUL_DIV_FACTOR2_SCALAR) {
          ${generateCostLookup(rowName(operation, 'scalar'))}

          ${generateCheckTransactionLimit(data.numberInputs, true, lhsName, rhsName)}
        } else if (scalarByte == FHE_MUL_DIV_FACTOR2_ENCRYPTED) {
          ${generateCostLookup(rowName(operation, 'nonScalar'))}

        ${generateCheckTransactionLimit(data.numberInputs, false, lhsName, rhsName)}
        } else {
          revert OnlyScalarOperationsAreSupported();
    }`;
      } else {
        output += `if (scalarByte == 0x01) {
          ${generateCostLookup(rowName(operation, 'scalar'))}

          ${generateCheckTransactionLimit(data.numberInputs, true, lhsName, rhsName)}
        } else {
          ${generateCostLookup(rowName(operation, 'nonScalar'))}

        ${generateCheckTransactionLimit(data.numberInputs, false, lhsName, rhsName)}
    }`;
      }
    } else if (data.scalar) {
      output += `if(scalarByte != 0x01) revert OnlyScalarOperationsAreSupported();`;
      output += `${generateCostLookup(rowName(operation, 'scalar'))}

                ${generateCheckTransactionLimit(data.numberInputs, true, lhsName, rhsName)} `;
    } else if (data.nonScalar) {
      output += `        if(scalarByte != 0x00) revert OnlyNonScalarOperationsAreSupported();`;
      output += `${generateCostLookup(rowName(operation, 'nonScalar'))}
      `;
      output += `${generateCheckTransactionLimit(data.numberInputs, false, lhsName, rhsName)}`;
    } else if (data.types) {
      output += `${generateCostLookup(rowName(operation, 'types'))}
      `;
      output += `${generateCheckTransactionLimit(data.numberInputs, false, lhsName, rhsName)}`;
    } else if (data.nBucketed) {
      output += generateNBucketedPriceChecks(data.nBucketed, data.numberInputs === -2 ? 'valueType' : 'resultType');
      output += data.numberInputs === -2 ? generateIsInTransactionLimit() : generateVariadicTransactionLimit();
    } else {
      throw new Error('No prices provided for the operation');
    }
    output += `
        }

    `;
  }

  return (
    output +
    `    /// @dev Meters an operation without encrypted inputs.
    function _adjustAndCheckFheTransactionLimitNoOps(uint256 opCost, address caller, bytes32 result) internal virtual;

    /// @dev Meters an operation with one encrypted input.
    function _adjustAndCheckFheTransactionLimitOneOp(
        uint256 opCost,
        address caller,
        bytes32 op1,
        bytes32 result
    ) internal virtual;

    /// @dev Meters an operation with two encrypted inputs.
    function _adjustAndCheckFheTransactionLimitTwoOps(
        uint256 opCost,
        address caller,
        bytes32 op1,
        bytes32 op2,
        bytes32 result
    ) internal virtual;

    /// @dev Meters an operation with three encrypted inputs.
    function _adjustAndCheckFheTransactionLimitThreeOps(
        uint256 opCost,
        address caller,
        bytes32 op1,
        bytes32 op2,
        bytes32 op3,
        bytes32 result
    ) internal virtual;

    /// @dev Meters an operation on an array of handles.
    function _adjustAndCheckFheTransactionLimitArray(
        uint256 opCost,
        address caller,
        bytes32[] calldata values,
        bytes32 result
    ) internal virtual;

    /// @dev Meters an operation on a handle and an array of handles.
    function _adjustAndCheckFheTransactionLimitValueAndArray(
        uint256 opCost,
        address caller,
        bytes32 value,
        bytes32[] calldata values,
        bytes32 result
    ) internal virtual;
  }
  `
  );
}

function generateNBucketedPriceChecks(
  nBucketed: Partial<Record<string, NBucketedCost>>,
  typeParam: string = 'resultType',
): string {
  const typeChecks = Object.entries(nBucketed)
    .map(([typeName, buckets]) => {
      if (!buckets) return '';
      const entries: Array<[number, Price]> = [];
      entries.push([10, buckets.le10]);
      if (buckets.le30 !== undefined) entries.push([30, buckets.le30]);
      if (buckets.le60 !== undefined) entries.push([60, buckets.le60]);
      if (buckets.le100 !== undefined) entries.push([100, buckets.le100]);
      if (buckets.le128 !== undefined) entries.push([128, buckets.le128]);

      const lines = entries.map(([threshold, cost], i) => {
        if (i === entries.length - 1) return `else opCost = ${packedCost(cost)};`;
        if (i === 0) return `if (n <= ${threshold}) opCost = ${packedCost(cost)};`;
        return `else if (n <= ${threshold}) opCost = ${packedCost(cost)};`;
      });
      return `if (${typeParam} == FheType.${typeName}) {
        ${lines.join('\n        ')}
      }`;
    })
    .join(' else ');
  return typeChecks + ' else { revert UnsupportedOperation(); }';
}

function generateVariadicTransactionLimit(): string {
  return `
    _adjustAndCheckFheTransactionLimitArray(opCost, caller, values, result);
  `;
}

function generateIsInTransactionLimit(): string {
  return `
    _adjustAndCheckFheTransactionLimitValueAndArray(opCost, caller, value, values, result);
  `;
}

function generateCheckTransactionLimit(
  numberInputs: number,
  isScalar: boolean,
  lhsName: string = 'lhs',
  rhsName: string = 'rhs',
): string {
  if (!isScalar) {
    switch (numberInputs) {
      case 0:
        return `_adjustAndCheckFheTransactionLimitNoOps(opCost, caller, result);`;
      case 1:
        return `_adjustAndCheckFheTransactionLimitOneOp(opCost, caller, ct, result);`;
      case 2:
        return `_adjustAndCheckFheTransactionLimitTwoOps(opCost, caller, ${lhsName}, ${rhsName}, result);`;
      case 3:
        return `_adjustAndCheckFheTransactionLimitThreeOps(opCost, caller, ${lhsName}, middle, ${rhsName}, result);`;
      default:
        throw new Error('Number of inputs for non-scalar must be less than 4');
    }
  } else {
    switch (numberInputs) {
      case 0:
        throw new Error('Number of inputs must be greater than 0 if scalar');
      case 1:
        return `_adjustAndCheckFheTransactionLimitNoOps(opCost, caller, result);`;
      case 2:
        return `_adjustAndCheckFheTransactionLimitOneOp(opCost, caller, ${lhsName}, result);`;
      default:
        throw new Error('Number of inputs for scalar must be less than 3');
    }
  }
}

type RowVariant = 'scalar' | 'nonScalar' | 'types';
const ROW_VARIANTS: RowVariant[] = ['scalar', 'nonScalar', 'types'];

type CostSlots = {
  /** Slot of each priced type, from 0, in FheType order. */
  slotOf: Map<string, number>;
  /** 4 bits per FheType value: 0 for a type without prices, else its slot plus 1. */
  word: bigint;
  legend: string;
};

/** Checks that every work and latency is an integer from 1 to 2^32 - 1, the range of a cost slot's half. */
function checkPrices(priceData: PriceData): void {
  const prices: Price[] = [];
  for (const data of Object.values(priceData)) {
    for (const variant of ROW_VARIANTS) {
      prices.push(...(Object.values(data[variant] ?? {}) as Price[]));
    }
    for (const buckets of Object.values(data.nBucketed ?? {})) {
      prices.push(...(Object.values(buckets ?? {}) as Price[]));
    }
  }
  for (const { work, latency } of prices) {
    for (const value of [work, latency]) {
      if (!Number.isInteger(value) || value < 1 || value > MAX_PRICE) {
        throw new Error(`A price must be an integer from 1 to ${MAX_PRICE}, got ${value}`);
      }
    }
  }
}

/** Gives each type that a cost row prices a slot, in FheType order. */
function costSlots(priceData: PriceData, fheTypes: FheTypeInfo[]): CostSlots {
  const priced = new Set<string>();
  for (const data of Object.values(priceData)) {
    for (const variant of ROW_VARIANTS) {
      Object.keys(data[variant] ?? {}).forEach((type) => priced.add(type));
    }
  }
  const types = fheTypes.filter((info) => priced.has(info.type)).sort((a, b) => a.value - b.value);
  if (types.length !== priced.size) {
    throw new Error(`The price file prices an unknown type: ${[...priced].join(', ')}`);
  }
  if (types.length > SLOTS_PER_ROW) {
    throw new Error(`A cost row has ${SLOTS_PER_ROW} slots, but the price file prices ${types.length} types`);
  }
  const slotOf = new Map<string, number>();
  let word = 0n;
  types.forEach((info, slot) => {
    if (info.value >= 64) {
      throw new Error(`COST_SLOTS covers FheType values below 64, but ${info.type} is ${info.value}`);
    }
    slotOf.set(info.type, slot);
    word |= BigInt(slot + 1) << BigInt(info.value * 4);
  });
  const legend = types.map((info, slot) => `${info.type} ${slot + 1}`).join(', ');
  return { slotOf, word, legend };
}

function hex256(word: bigint): string {
  return `0x${word.toString(16).padStart(64, '0')}`;
}

function packedCost({ work, latency }: Price): string {
  return `(${work} << 32) | ${latency}`;
}

function rowName(operation: string, variant: RowVariant): string {
  const name = operation.replace(/([A-Z])/g, '_$1').toUpperCase();
  return `${name}${variant === 'scalar' ? '_SCALAR' : ''}_COSTS`;
}

function generateCostRows(operation: string, data: PriceData[keyof PriceData], slots: CostSlots): string {
  let output = '';
  for (const variant of ROW_VARIANTS) {
    const prices = data[variant];
    if (!prices) continue;
    const words = [0n, 0n];
    const listed: string[] = [];
    for (const [type, { work, latency }] of Object.entries(prices) as Array<[string, Price]>) {
      const slot = slots.slotOf.get(type)!;
      words[Math.floor(slot / 4)] |= ((BigInt(work) << 32n) | BigInt(latency)) << (BigInt(slot % 4) * SLOT_BITS);
      listed.push(`${type} ${work}/${latency}`);
    }
    const name = rowName(operation, variant);
    const label = `${operation.charAt(0).toUpperCase() + operation.slice(1)}${variant === 'scalar' ? ', scalar' : ''}`;
    output += `
    /// ${label}, work/latency: ${listed.join(', ')}.
    uint256 private constant ${name}_0 = ${hex256(words[0])};
    uint256 private constant ${name}_1 = ${hex256(words[1])};
`;
  }
  return output;
}

function generateCostLookup(name: string): string {
  return `opCost = _cost(${name}_0, ${name}_1, resultType);`;
}
