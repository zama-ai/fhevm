test('a host name that is not an identifier is quoted', () => {
  const text = fixture((config) => {
    const hosts = (config as Mutable).networks.testnet.hosts;
    hosts['polygon-amoy'] = hosts.polygon_amoy;
    delete hosts.polygon_amoy;
  });
  assert.ok(
    renderChainConstants(parseChainsConfig(text)).includes("      'polygon-amoy': {\n        name: 'polygon-amoy',"),
  );
});

const REJECTIONS: ReadonlyArray<[string, string | ((config: Record<string, unknown>) => void), string]> = [
  ['invalid JSON', '{', 'not valid JSON'],
  [
    'a bad commit',
    (c) => ((c as Mutable).source.commit = 'deadbeef'),
    '#source.commit: expected a 40-hex registry commit',
  ],
  ['a missing group', (c) => delete (c as Mutable).networks.devnet, "#networks: missing network group 'devnet'"],
  [
    'an unknown group',
    (c) => ((c as Mutable).networks.staging = (c as Mutable).networks.devnet),
    '#networks.staging: unknown network group',
  ],
  [
    'a bad relayer url',
    (c) => ((c as Mutable).networks.mainnet.relayerUrl = 'relayer'),
    'networks.mainnet.relayerUrl: expected an http(s) URL',
  ],
  [
    'a missing required contract',
    (c) => delete (c as Mutable).networks.mainnet.hosts.ethereum.contracts.acl,
    "hosts.ethereum.contracts: missing required contract 'acl'",
  ],
  [
    'an unknown contract',
    (c) => ((c as Mutable).networks.mainnet.gateway.contracts.oracle = { address: A(9) }),
    'gateway.contracts.oracle: unknown contract',
  ],
  [
    'a bad address',
    (c) => ((c as Mutable).networks.mainnet.hosts.ethereum.contracts.acl.address = '0x12'),
    'contracts.acl.address: expected a 20-byte hex address',
  ],
  [
    'a duplicate chain id within a group',
    (c) => ((c as Mutable).networks.testnet.hosts.polygon_amoy.id = 11155111),
    "hosts.polygon_amoy.id: chain id 11155111 already used by 'ethereum_sepolia'",
  ],
  [
    'a non-integer chain id',
    (c) => ((c as Mutable).networks.mainnet.gateway.id = 1.5),
    'gateway.id: expected a positive integer chain id',
  ],
  [
    'no hosts',
    (c) => ((c as Mutable).networks.mainnet.hosts = {}),
    'networks.mainnet.hosts: expected at least one host chain',
  ],
];

for (const [label, mutate, message] of REJECTIONS) {
  test(`refuses ${label} by name`, () => {
    const text = typeof mutate === 'string' ? mutate : fixture(mutate);
    assert.throws(
      () => parseChainsConfig(text),
      (error: unknown) => error instanceof Error && error.message.includes(message),
    );
  });
}

test('write mode creates the face; check mode reports missing, identical and different', async () => {
  const { mkdtempSync, rmSync, writeFileSync, readFileSync: read } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const { generateChainConstants, CHAIN_CONSTANTS_FACE_PATH } = await import('../base/generate-chain-constants.ts');
  const workspace = mkdtempSync(join(tmpdir(), 'fhevm-npm-chain-constants-'));
  try {
    writeFileSync(join(workspace, 'fhevm-chains.config.json'), fixture());
    const face = join(workspace, ...CHAIN_CONSTANTS_FACE_PATH);

    assert.deepEqual(generateChainConstants({ workspaceRoot: workspace, check: true }), {
      path: face,
      status: 'missing',
    });

    assert.deepEqual(generateChainConstants({ workspaceRoot: workspace, check: false }), {
      path: face,
      status: 'identical',
    });
    assert.equal(read(face, 'utf8'), renderChainConstants(parseChainsConfig(fixture())));
    assert.deepEqual(generateChainConstants({ workspaceRoot: workspace, check: true }), {
      path: face,
      status: 'identical',
    });

    writeFileSync(face, read(face, 'utf8').replace(A(0x201), A(0x999)));
    assert.deepEqual(generateChainConstants({ workspaceRoot: workspace, check: true }), {
      path: face,
      status: 'different',
    });
  } finally {
    rmSync(workspace, { recursive: true, force: true });
  }
});

test('the command refuses a workspace with no chains config, by name', async () => {
  const { mkdtempSync, rmSync } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const { generateChainConstants } = await import('../base/generate-chain-constants.ts');
  const workspace = mkdtempSync(join(tmpdir(), 'fhevm-npm-chain-constants-'));
  try {
    assert.throws(
      () => generateChainConstants({ workspaceRoot: workspace, check: true }),
      /fhevm-chains\.config\.json not found — run `fhevm-npm sync-fhevm-chains --latest`/,
    );
  } finally {
    rmSync(workspace, { recursive: true, force: true });
  }
});
