const COMMIT = 'ff8137fbf40beeec15abae26fca6cf9172052a8c';
const A = (n: number): string => `0x${n.toString(16).padStart(40, '0')}`;

const GATEWAY = (base: number, legacy = false) => ({
  ciphertextCommits: { address: A(base + 1) },
  decryption: { address: A(base + 2) },
  gatewayConfig: { address: A(base + 3) },
  inputVerification: { address: A(base + 4) },
  ...(legacy ? {} : { kmsGeneration: { address: A(base + 5) }, multichainAcl: { address: A(base + 6) } }),
  pauserSet: { address: A(base + 7) },
});

const HOST = (base: number, v13: boolean) => ({
  acl: { address: A(base + 1) },
  fhevmExecutor: { address: A(base + 2) },
  hcuLimit: { address: A(base + 3) },
  inputVerifier: { address: A(base + 4) },
  ...(v13 ? { kmsGeneration: { address: A(base + 5) } } : {}),
  kmsVerifier: { address: A(base + 6) },
  pauserSet: { address: A(base + 7) },
  ...(v13 ? { protocolConfig: { address: A(base + 8) } } : {}),
});

// Sepolia (11155111) is a host of BOTH testnet and devnet, as in the real registry.
