////////////////////////////////////////////////////////////////////////////////
//
// Clients of the cleartext stack whose pad shares come from relayer-http (`POST /v4/pad-decrypt`) instead of the
// chain: the cleartext runtime with one relayer function, `fetchPadShares`, taken from the HTTP relayer module.
// Everything else stays cleartext: the ethereum module, user decryption, the pad reconstruction (the TKMS WASM
// reconstruction is not exposed yet). Both clients share the runtime, so a transport key pair generated by one is
// usable by the other. Test only.
//
// relayer-http, its mock KMS connectors and the stack: relayer-http/dev/README.md, "Pad decryption".
//
////////////////////////////////////////////////////////////////////////////////

/** relayer-http's URL, from `RELAYER_HTTP_URL`; the tests of this directory run only when it is set. */
export const RELAYER_HTTP_URL: string | undefined = process.env.RELAYER_HTTP_URL;

let runtime: FhevmRuntime | undefined;

/** One runtime for the whole run, as the SDK's own clients share theirs. */
function getRelayerHttpRuntime(): FhevmRuntime {
  runtime ??= createFhevmRuntime({
    ethereum: cleartextEthereumModule().ethereum,
    relayer: Object.freeze({
      ...cleartextRelayerModule().relayer,
      fetchPadShares: relayerModule().relayer.fetchPadShares,
    }),
    config: getFhevmRuntimeConfig(),
  });
  return runtime;
}

/** `chain` with its relayer URL pointed at relayer-http. */
function withRelayerHttp<chain extends FhevmChain>(chain: chain): chain {
  if (RELAYER_HTTP_URL === undefined) {
    throw new Error('RELAYER_HTTP_URL is not set');
  }
  return defineFhevmChain({ ...chain, fhevm: { ...chain.fhevm, relayerUrl: RELAYER_HTTP_URL } });
}

export function createRelayerHttpEncryptWithPadClient<
  chain extends FhevmChain,
  provider extends EthersT.ContractRunner,
>(parameters: {
  readonly provider: provider;
  readonly chain: chain;
  readonly options?: FhevmEncryptOptions | undefined;
}): FhevmEncryptWithPadClient<chain, WithEncryptWithPad, provider> {
  const c = createCoreFhevm(PRIVATE_ETHERS_TOKEN, {
    chain: withRelayerHttp(parameters.chain),
    runtime: getRelayerHttpRuntime(),
    client: parameters.provider,
    options: parameters.options,
  });
  return c.extend(baseActions).extend(encryptWithPadActions);
}

export function createRelayerHttpDecryptClient<
  chain extends FhevmChain,
  provider extends EthersT.ContractRunner,
>(parameters: {
  readonly provider: provider;
  readonly chain: chain;
  readonly options?: FhevmDecryptOptions | undefined;
}): FhevmDecryptClient<chain, WithDecrypt, provider> {
  const c = createCoreFhevm(PRIVATE_ETHERS_TOKEN, {
    chain: withRelayerHttp(parameters.chain),
    runtime: getRelayerHttpRuntime(),
    client: parameters.provider,
    options: parameters.options,
  });
  return c.extend(baseActions).extend(decryptActions);
}
