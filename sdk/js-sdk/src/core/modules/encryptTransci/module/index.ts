import type { FhevmRuntime } from '../../../types/coreFhevmRuntime.js';
import type {
  GetTkmsModuleInfoParameters,
  GetTkmsPublicKeyHexParameters,
  SerializeTkmsPrivateKeyParameters,
} from '../../decrypt/types.js';
import type { EncryptTransciModuleFactory, ReconstructPadsModuleParameters } from '../types.js';
import { getTkmsModuleInfo, initTkmsModule } from '../../decrypt/module/init-p.js';
import { generateTkmsPrivateKey, getTkmsPublicKeyHex, serializeTkmsPrivateKey } from '../../decrypt/module/api-p.js';
import { reconstructPads } from '../../../kms/reconstructPads-p.js';

//////////////////////////////////////////////////////////////////////////////
// encryptTransciModule
//
// Shares the TKMS WASM instance with the decrypt module (one instance per
// runtime), including its transport key functions: a key pair generated here
// is interchangeable with one generated by the decrypt module.
//
// Note: `reconstructPads` only supports the cleartext share encoding for now;
// the ML-KEM hybrid decryption and threshold share decoding of real responses
// are not exposed by the TKMS WASM yet.
//////////////////////////////////////////////////////////////////////////////

export const encryptTransciModule: EncryptTransciModuleFactory = (runtime: FhevmRuntime) => {
  return Object.freeze({
    encryptTransci: Object.freeze({
      initTkmsModule: async () => {
        await initTkmsModule(runtime);
      },
      getTkmsModuleInfo: (args: GetTkmsModuleInfoParameters) => getTkmsModuleInfo(args),
      reconstructPads: (args: ReconstructPadsModuleParameters) => reconstructPads(runtime.ethereum, args),
      generateTkmsPrivateKey: () => generateTkmsPrivateKey(runtime),
      serializeTkmsPrivateKey: (args: SerializeTkmsPrivateKeyParameters) => serializeTkmsPrivateKey(runtime, args),
      getTkmsPublicKeyHex: (args: GetTkmsPublicKeyHexParameters) => getTkmsPublicKeyHex(runtime, args),
    }),
  });
};
