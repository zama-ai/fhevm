// The JS renderer omits constant nodes. Use their types and Anchor's original value strings:
// nodes-from-anchor parses wide integers through Number, which loses precision before rendering.
export function renderProgramConstants(constants, anchorConstants) {
  if (constants.length !== anchorConstants.length) throw new Error('Anchor constant nodes are missing');
  const declarations = constants.map((constant, index) => {
    const { name, value } = anchorConstants[index];
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`Invalid constant name: ${name}`);
    let type = constant.type;
    while (['fixedSizeTypeNode', 'sizePrefixTypeNode'].includes(type.kind)) type = type.type;
    if (type.kind === 'numberTypeNode') {
      const integer = /^([ui])(\d+)$/.exec(type.format);
      if (integer) {
        const wide = Number(integer[2]) >= 64;
        const literal = BigInt(value);
        return `export const ${name}: ${wide ? 'bigint' : 'number'} = ${literal}${wide ? 'n' : ''};`;
      }
      if (/^f(32|64)$/.test(type.format) && Number.isFinite(Number(value))) {
        return `export const ${name}: number = ${Number(value)};`;
      }
    }
    if (
      type.kind === 'bytesTypeNode' ||
      (type.kind === 'arrayTypeNode' && type.item.kind === 'numberTypeNode' && type.item.format === 'u8')
    ) {
      const bytes = JSON.parse(value);
      if (!Array.isArray(bytes) || bytes.some((byte) => !Number.isInteger(byte) || byte < 0 || byte > 255)) {
        throw new Error(`Invalid byte constant: ${name}`);
      }
      return `export const ${name}: Uint8Array = new Uint8Array(${JSON.stringify(bytes)});`;
    }
    if (type.kind === 'booleanTypeNode' || type.kind === 'stringTypeNode') {
      const parsed = JSON.parse(value);
      const expected = type.kind === 'booleanTypeNode' ? 'boolean' : 'string';
      if (typeof parsed !== expected) throw new Error(`Invalid ${expected} constant: ${name}`);
      return `export const ${name}: ${expected} = ${JSON.stringify(parsed)};`;
    }
    throw new Error(`Unsupported program constant type: ${name} (${type.kind})`);
  });
  return (
    '/** This code was AUTOGENERATED from the program IDL. */\n\n' +
    (declarations.length ? declarations.join('\n') : 'export {};') +
    '\n'
  );
}
