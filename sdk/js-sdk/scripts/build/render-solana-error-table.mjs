import { snakeCase } from 'codama';

// Codama renders a program's errors from its IDL, scoped to that program's address. A library
// crate's errors appear in no IDL and are raised by whichever app program links the crate, so
// they render here from the crate's own table (build-zama-fhe-errors.sh), matched on the code.
export function renderErrorTable(name, errors) {
  const prefix = `${snakeCase(name).toUpperCase()}_ERROR__`;
  const type = `${name[0].toUpperCase()}${name.slice(1)}Error`;
  const constant = ({ name }) => `${prefix}${snakeCase(name).toUpperCase()}`;
  return [
    `/** This code was AUTOGENERATED from the committed ${snakeCase(name)}_errors.json. */`,
    `import { isSolanaError, SOLANA_ERROR__INSTRUCTION_ERROR__CUSTOM } from '@solana/kit';`,
    '',
    ...errors.map((error) => `/** ${error.name}: ${error.msg} */\nexport const ${constant(error)} = ${error.code};`),
    '',
    `export type ${type} = ${errors.map((error) => `typeof ${constant(error)}`).join(' | ')};`,
    '',
    `const ${name}ErrorMessages: Record<${type}, string> = {`,
    ...errors.map((error) => `  [${constant(error)}]: ${JSON.stringify(error.msg)},`),
    '};',
    '',
    `export function get${type}Message(code: ${type}): string {`,
    `  return ${name}ErrorMessages[code];`,
    '}',
    '',
    `/** True when an instruction failed with one of these codes, whichever app program raised it. */`,
    `export function is${type}(error: unknown, code?: ${type}): boolean {`,
    `  if (!isSolanaError(error, SOLANA_ERROR__INSTRUCTION_ERROR__CUSTOM)) return false;`,
    `  return code === undefined ? error.context.code in ${name}ErrorMessages : error.context.code === code;`,
    '}',
    '',
  ].join('\n');
}
