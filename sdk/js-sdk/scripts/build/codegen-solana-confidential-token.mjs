function idlUrl(name) {
  return fileURLToPath(new URL(`../../../../coprocessor/fhevm-engine/host-listener/idl/${name}`, import.meta.url));
}

// The demo-only programs' IDLs live with the dapp that consumes their generated clients
// (synced by solana/scripts/sync-zama-host-idl.sh).
function demoIdlUrl(name) {
  return fileURLToPath(new URL(`../../../../solana/demo-dapp/idl/${name}`, import.meta.url));
}

// The specimen consumer programs' IDLs live inside each program directory, so the specimen stays
// self-contained for anyone copying it (synced by solana/scripts/sync-zama-host-idl.sh).
function specimenIdlUrl(program, name) {
  return fileURLToPath(new URL(`../../../../solana/programs/${program}/idl/${name}`, import.meta.url));
}

function snapshot(path) {
  if (!existsSync(path)) return new Map();
  path = realpathSync(path);
  return new Map(
    readdirSync(path, { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => [
        `${entry.parentPath}/${entry.name}`.slice(path.length + 1),
        readFileSync(`${entry.parentPath}/${entry.name}`, 'utf8'),
      ])
      .sort(([left], [right]) => left.localeCompare(right)),
  );
}

