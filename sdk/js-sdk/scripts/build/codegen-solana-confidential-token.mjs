// zama-host derives an app's meter from the app its stores name at run time (block_cap.rs), so no
// instruction declares the meter's seeds. Only the prefix comes from the IDL; the (appProgram, scope)
// order is typed here and checked by pda-golden.test.ts.
const hcuBlockMeterSeed = hostIdl.constants.find(({ name }) => name === 'HCU_BLOCK_METER_SEED');
if (!hcuBlockMeterSeed) throw new Error('HCU_BLOCK_METER_SEED is missing from the committed zama-host IDL');
const hcuBlockMeter = pdaNode({
  name: 'hcuBlockMeter',
  seeds: [
    constantPdaSeedNodeFromBytes('base58', getBase58Decoder().decode(Uint8Array.from(JSON.parse(hcuBlockMeterSeed.value)))),
    variablePdaSeedNode('appProgram', publicKeyTypeNode()),
    variablePdaSeedNode('scope', publicKeyTypeNode()),
  ],
});

let stale = false;
const deploymentProgramIds = {};
for (const target of targets) {
  const before = check ? snapshot(target.generatedPath) : undefined;
  const temporaryRoot = mkdtempSync(`${tmpdir()}/fhevm-codama-`);
  const temporaryGeneratedPath = `${temporaryRoot}/generated`;

  const anchorIdl = JSON.parse(readFileSync(target.idlPath, 'utf8'));
  deploymentProgramIds[anchorIdl.metadata.name] = anchorIdl.address;
  const codama = createFromRoot(rootNodeFromAnchor(anchorIdl));
  const product = [idlUrl('zama_host.json'), idlUrl('confidential_token.json')].includes(target.idlPath);
  if (product) {
    codama.update(
      updateProgramsVisitor({
        [codama.getRoot().program.name]: {
          pdas: [
            ...codama.getRoot().program.pdas,
            eventAuthority,
            ...(target === hostTarget ? [hcuBlockMeter] : []),
          ],
        },
      }),
    );
    codama.update(
      updateInstructionsVisitor(
        Object.fromEntries(
          codama.getRoot().program.instructions.map(({ name, accounts }) => [
            name,
            {
              accounts: Object.fromEntries(
                accounts
                  .filter(({ name }) => name === 'eventAuthority' || name === 'program')
                  .map(({ name }) => [
                    name,
                    { defaultValue: name === 'eventAuthority' ? pdaValueNode(eventAuthority) : programIdValueNode() },
                  ]),
              ),
            },
          ]),
        ),
      ),
    );
  }
  const foreignPdaLinks = {};
  // Targets whose accounts pin zama-host PDAs default them through the `@fhevm/solana-zama-host` finders.
  if (target.linkHostPdas) {
    const hostPdas = [...hostProgram.pdas, eventAuthority];
    // updateInstructionsVisitor fills local seed defaults and drops a linked PDA's programId.
    // Preserve the foreign program binding instead of resolving it against this program's PDAs.
    codama.update(
      bottomUpTransformerVisitor([
        {
          select: '[instructionAccountNode]',
          transform(account) {
            const value = account.defaultValue;
            const foreign = value?.pda;
            if (foreign?.kind !== 'pdaNode' || foreign.programId !== hostIdl.address) return account;
            const matches = hostPdas.filter(
              (pda) =>
                pda.seeds.length === foreign.seeds.length &&
                pda.seeds.every(
                  (seed, i) =>
                    seed.kind === 'variablePdaSeedNode' || JSON.stringify(seed) === JSON.stringify(foreign.seeds[i]),
                ),
            );
            if (matches.length !== 1) throw new Error(`Cannot link foreign PDA: ${account.name}`);
            const hostPda = matches[0];
            foreignPdaLinks[hostPda.name] = 'zamaHost';
            const seeds = hostPda.seeds.flatMap((seed, i) => {
              if (seed.kind !== 'variablePdaSeedNode') return [];
              const source = foreign.seeds[i];
              let binding =
                source.kind === 'variablePdaSeedNode'
                  ? value.seeds.find(({ name }) => name === source.name)?.value
                  : source.value;
              if (
                seed.type.kind === 'publicKeyTypeNode' &&
                binding?.kind === 'bytesValueNode' &&
                binding.encoding === 'base58'
              ) {
                binding = publicKeyValueNode(binding.data);
              }
              if (!binding) throw new Error(`Missing foreign PDA seed: ${account.name}.${seed.name}`);
              return [pdaSeedValueNode(seed.name, binding)];
            });
            return {
              ...account,
              defaultValue: pdaValueNode(pdaLinkNode(hostPda.name), seeds, accountValueNode('zamaProgram')),
            };
          },
        },
      ]),
    );
  }
  const program = codama.getRoot().program;
  // Host types render once, in `@fhevm/solana-zama-host`; a linked app client imports them from there.
  const foreignTypeLinks = target.linkHostPdas
    ? Object.fromEntries(
        (program.definedTypes ?? [])
          .filter(({ name }) => hostTypeNames.has(name))
          .map(({ name }) => [name, 'zamaHost']),
      )
    : {};
  for (const name of Object.keys(foreignTypeLinks)) {
    if (!hostClientTypes.has(name)) {
      throw new Error(`${name} links to @fhevm/solana-zama-host, which does not export it: keep it in the zama-host target`);
    }
  }
  const keep = target.keep;
  if (keep) {
    for (const [kind, names] of Object.entries(keep)) {
      const present = new Set((program[kind] ?? []).map((node) => node.name));
      for (const name of names) {
        if (!present.has(name)) throw new Error(`Required Codama ${kind} node is missing: ${name}`);
      }
    }
  }

  const selectors = [
    ...(keep
      ? [
          ...program.instructions
            .filter(({ name }) => !keep.instructions.has(name))
            .map(({ name }) => `[instructionNode]${name}`),
          ...program.accounts
            .filter(({ name }) => !(keep.accounts ?? new Set()).has(name))
            .map(({ name }) => `[accountNode]${name}`),
          ...(program.definedTypes ?? [])
            .filter(({ name }) => !keep.definedTypes.has(name))
            .map(({ name }) => `[definedTypeNode]${name}`),
          ...program.pdas.filter(({ name }) => keep.pdas && !keep.pdas.has(name)).map(({ name }) => `[pdaNode]${name}`),
        ]
      : []),
    ...Object.keys(foreignTypeLinks).map((name) => `[definedTypeNode]${name}`),
    ...(target.keepErrors ? [] : program.errors.map(({ name }) => `[errorNode]${name}`)),
    ...(program.events ?? []).map(({ name }) => `[eventNode]${name}`),
    ...(program.constants ?? []).map(({ name }) => `[constantNode]${name}`),
  ];
  codama.update(deleteNodesVisitor(selectors));
  const keptEvents = (program.events ?? []).filter(({ name }) => keep?.events?.has(name));
  if (keptEvents.length > 0) {
    codama.update(
      updateProgramsVisitor({
        [program.name]: {
          definedTypes: [
            ...(codama.getRoot().program.definedTypes ?? []),
            ...keptEvents.map(({ name, docs, data }) => definedTypeNode({ name, docs, type: data })),
          ],
        },
      }),
    );
  }
  // An optional PDA is an opt-in account. Its presence can take a write lock or change policy,
  // so absence must stay absence; callers that need it use the generated finder.
  if ([idlUrl('zama_host.json'), idlUrl('confidential_token.json')].includes(target.idlPath)) {
    codama.update(
      updateInstructionsVisitor(
        Object.fromEntries(
          codama.getRoot().program.instructions.map(({ name, accounts }) => [
            name,
            {
              accounts: Object.fromEntries(
                accounts
                  .filter((account) => account.isOptional && account.defaultValue?.kind === 'pdaValueNode')
                  .map((account) => [account.name, { defaultValue: undefined }]),
              ),
            },
          ]),
        ),
      ),
    );
  }

  // quit's user signs a pending batch's quit but not a refunding batch's (quit.rs), which the IDL
  // cannot express: the client takes a signer or an address.
  if (target.idlPath === demoIdlUrl('confidential_batcher.json')) {
    codama.update(updateInstructionsVisitor({ quit: { accounts: { user: { isSigner: 'either' } } } }));
  }

  await codama.accept(
    renderVisitor(temporaryRoot, {
      generatedFolder: 'generated',
      importExtension: 'js',
      syncPackageJson: false,
      linkOverrides: { pdas: foreignPdaLinks, definedTypes: foreignTypeLinks },
      dependencyMap: { zamaHost: '@fhevm/solana-zama-host' },
      dependencyVersions: {
        '@fhevm/solana-zama-host': JSON.parse(
          readFileSync(`${sdkRoot}/../../solana/clients/zama-host/package.json`, 'utf8'),
        ).version,
      },
    }),
  );
  writeFileSync(`${temporaryGeneratedPath}/programAddress.ts`, target.programAddress(program, anchorIdl));
  writeFileSync(
    `${temporaryGeneratedPath}/constants.ts`,
    renderProgramConstants(program.constants ?? [], anchorIdl.constants ?? [], anchorIdl.events ?? []),
  );
  if (target.errorTable) {
    writeFileSync(
      `${temporaryGeneratedPath}/${target.errorTable.name}Errors.ts`,
      renderErrorTable(target.errorTable.name, JSON.parse(readFileSync(target.errorTable.path, 'utf8'))),
    );
  }
  rmSync(`${temporaryGeneratedPath}/programs`, { force: true, recursive: true });
  rmSync(`${temporaryGeneratedPath}/index.ts`, { force: true });

  // Recovery needs the canonical signing seeds.
  const seedEncoderFiles = new Set(
    target.idlPath === idlUrl('confidential_token.json')
      ? ['vaultAuthority.ts', 'totalSupplyAuthority.ts']
      : target.idlPath === demoIdlUrl('confidential_batcher.json')
        ? ['batchAuthority.ts']
        : target.idlPath === demoIdlUrl('demo_vault.json')
          ? ['vaultAuthority.ts']
          : [],
  );
  for (const entry of readdirSync(temporaryGeneratedPath, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.ts')) continue;
    const file = `${entry.parentPath}/${entry.name}`;
    let source = readFileSync(file, 'utf8').replace(/(['"])\.\.\/programs\/index\.js\1/g, '$1../programAddress.js$1');
    if (file.includes('/pdas/') && seedEncoderFiles.has(entry.name)) {
      let renderedSeedEncoder = false;
      source = source.replace(
        /(export async function find(\w+)Pda\([\s\S]*?return await getProgramDerivedAddress\(\{\s*programAddress,\s*)seeds: (\[[\s\S]*?\]),(\s*\}\);\s*\})/,
        (_, prefix, name, seeds, suffix) => {
          renderedSeedEncoder = true;
          const seedType = source.includes(`export type ${name}Seeds`) ? `${name}Seeds` : undefined;
          return (
            `${prefix}seeds: get${name}PdaSeeds(${seedType ? 'seeds' : ''}),${suffix}\n` +
            `\nexport function get${name}PdaSeeds(${seedType ? `seeds: ${seedType}` : ''}) {\n` +
            `  return ${seeds};\n}\n`
          );
        },
      );
      if (!renderedSeedEncoder) throw new Error(`Cannot render PDA seed encoder: ${file}`);
      seedEncoderFiles.delete(entry.name);
    }
    writeFileSync(file, await format(source, { ...prettierOptions, parser: 'typescript' }));
  }
  if (seedEncoderFiles.size > 0) {
    throw new Error(`Missing PDA seed encoder files: ${[...seedEncoderFiles].join(', ')}`);
  }

  if (check) {
    const after = snapshot(temporaryGeneratedPath);
    if (JSON.stringify([...before]) !== JSON.stringify([...after])) stale = true;
  } else {
    rmSync(target.generatedPath, { force: true, recursive: true });
    cpSync(temporaryGeneratedPath, target.generatedPath, { recursive: true });
  }
  rmSync(temporaryRoot, { force: true, recursive: true });
}

// Derive deployment identities from the same IDLs as all application clients.
const identitiesPath = `${sdkRoot}/../../solana/deploy/src/generated/program-ids.json`;
const identities = JSON.stringify(deploymentProgramIds, null, 2) + '\n';
if (check) {
  if (!existsSync(identitiesPath) || readFileSync(identitiesPath, 'utf8') !== identities) stale = true;
} else {
  writeFileSync(identitiesPath, identities);
}

if (check && stale) {
  throw new Error('Generated Solana client is stale; run npm run codegen:solana');
}
