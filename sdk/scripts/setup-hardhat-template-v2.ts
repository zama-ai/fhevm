#!/usr/bin/env node
//
// Installs `hardhat/v2/fhevm-hardhat-template` against workspace candidate directories.
//
// Usage: npm run setup:hardhat-template-v2
//
// Run from anywhere: the workspace root is found via `npm prefix`, falling back to this file's parent.
//
// ## Why this lives here and not in the template
//
// The template is mirrored BYTE-FOR-BYTE to github.com/zama-ai/fhevm-hardhat-template. Anything in it
// that only makes sense inside this workspace would ship to the public repo, so the workspace's own
// machinery has to sit outside the mirrored directory. That is also why the template's `package.json`
// has no `setup` script: it would be a script the public copy cannot run.
//
// ## Why `--install-links` is required
//
// `package.json` names the two candidate directories directly, so npm never looks them up on the registry.
// `--install-links` makes npm pack and copy those directories instead of symlinking their source trees,
// exercising the same `files` and ignore rules as publication without creating persistent `.tgz` files.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The template, relative to the workspace root. */
const TEMPLATE_REL = join('hardhat', 'v2', 'fhevm-hardhat-template');

/**
 * Everything regenerated by a setup, removed before one. The template's own `.gitignore` lists exactly
 * these, which is the check that nothing tracked is being deleted.
 *
 * A from-scratch install rather than an incremental one, because npm can treat the same candidate
 * version as already satisfied after its contents change. `package-lock.json` can likewise preserve an
 * older packed copy. Both failure modes are silent, so setup removes the installed tree and lockfile.
 */
const CLEAN_PATHS = ['node_modules', 'package-lock.json', 'artifacts', 'cache', 'types'];

type Manifest = {
  readonly dependencies?: Readonly<Record<string, string>>;
  readonly devDependencies?: Readonly<Record<string, string>>;
  readonly workspaces?: readonly string[];
};

/** The leading comment block doubles as the help text, so there is only one copy of it. */
function usage(): void {
  const source = readFileSync(fileURLToPath(import.meta.url), 'utf8');
  for (const line of source.split('\n').slice(1)) {
    if (!line.startsWith('//')) break;
    console.log(line.replace(/^\/\/ ?/, ''));
  }
}

function parseArgs(argv: readonly string[]): void {
  for (const arg of argv) {
    if (arg === '-h' || arg === '--help') {
      usage();
      process.exit(0);
    }
    console.error(`Error: unknown argument '${arg}'. Try --help.`);
    process.exit(1);
  }
}

function readManifest(file: string): Manifest {
  return JSON.parse(readFileSync(file, 'utf8')) as Manifest;
}

function workspaceRoot(): string {
  try {
    const prefix = execFileSync('npm', ['prefix'], { encoding: 'utf8' }).trim();
    if (prefix && existsSync(join(prefix, 'package.json')) && readManifest(join(prefix, 'package.json')).workspaces) {
      return prefix;
    }
  } catch {
    // npm is not on PATH, or we are outside a package — fall through to the path-based guess.
  }
  return dirname(dirname(fileURLToPath(import.meta.url)));
}

/** Every `file:` candidate the template's manifest declares, resolved against the template. */
function candidateSpecs(templateDir: string): { name: string; absolute: string }[] {
  const manifest = readManifest(join(templateDir, 'package.json'));
  const all = { ...(manifest.dependencies ?? {}), ...(manifest.devDependencies ?? {}) };
  return Object.entries(all)
    .filter(([, spec]) => spec.startsWith('file:'))
    .map(([name, spec]) => ({ name, absolute: resolve(templateDir, spec.slice('file:'.length)) }));
}

function main(): void {
  parseArgs(process.argv.slice(2));
  const templateDir = join(workspaceRoot(), TEMPLATE_REL);

  if (!existsSync(join(templateDir, 'package.json'))) {
    console.error(`   ❌ no template at ${templateDir}`);
    process.exit(1);
  }

  const specs = candidateSpecs(templateDir);
  if (specs.length === 0) {
    console.error('   ❌ the template package.json declares no `file:` candidate directory.');
    process.exit(1);
  }

  console.log('📦 hardhat template v2: the @fhevm packages come from workspace candidate directories');

  const missing = specs.filter(({ absolute }) => !existsSync(absolute));
  for (const { name, absolute } of specs) {
    if (existsSync(absolute)) console.log(`   ${name.padEnd(33)} ← ${absolute}`);
  }

  if (missing.length > 0) {
    console.error('');
    console.error(`   ❌ ${missing.length} candidate directory/directories do not exist:`);
    for (const { name, absolute } of missing) console.error(`        ${name}\n          ${absolute}`);
    process.exit(1);
  }

  const removed: string[] = [];
  for (const name of CLEAN_PATHS) {
    const path = join(templateDir, name);
    if (!existsSync(path)) continue;
    rmSync(path, { recursive: true, force: true });
    removed.push(name);
  }
  console.log(`   🧹 ${removed.length === 0 ? 'nothing to clean' : `removed ${removed.join(', ')}`}`);

  const args = ['install', '--install-links', '--no-audit', '--no-fund'];
  console.log(`   npm ${args.join(' ')}   (in ${TEMPLATE_REL})`);
  execFileSync('npm', args, { cwd: templateDir, stdio: 'inherit' });

  console.log('   ✅ setup complete — run `npm test` in the template');
}

main();
