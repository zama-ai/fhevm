#!/usr/bin/env bash
#
# Start an anvil node and deploy the cleartext v13 stack onto it from the PRE-COMPILED bytecode blobs.
# Ctrl-C stops the node.
#
# Usage: ./scripts/anvil-local-v1.sh [--port PORT] [--no-check] [-v|--verbose]
#
#   --port PORT       anvil port (default: 8545)
#   --no-check        skip the post-deploy smoke check
#   -v, --verbose     print every step (forge's full deploy output)
#
# Three ways to get a local stack, fastest first:
#
#   anvil-fast.sh   anvil --init pkg/state/genesis.json           no deploy, no compile   (~1 s)
#   anvil-local.sh  deploy the committed blobs                    no address compile      (this script)
#   anvil.sh        compute addresses, compile pkg/src, deploy    full path               (~20 s)
#
# What makes this one quicker than anvil.sh is that it skips the compile-for-these-addresses round.
# scripts/deploy.sh has to compute the addresses first and then build pkg/src against them, because the
# addresses are baked into the contracts. Here they are baked in already: pkg/forge/src/_internal/
# LocalHostBytecode.sol ships bytecode compiled against the canonical address set, generated by
# `npm run generate:local-host-bytecode`. Deploying those blobs needs no solc pass over pkg/src.
#
# It is also a real deploy, unlike anvil-fast.sh: transactions, receipts, event logs and block history all
# exist afterwards. Use this when a test reads the deploy's events or needs the chain to look deployed-to;
# use anvil-fast.sh when you only need the end state.
#
# ## Restriction
#
# Canonical stack only. The addresses are compiled into the blobs, so the deployer is fixed: the package
# mnemonic at account index 5, starting at nonce 0. There is deliberately no --mnemonic here; for any other
# deployer use scripts/deploy.sh, which computes addresses to match.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACKAGE_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

PORT=8545
CHECK=1
VERBOSE=0

while [ $# -gt 0 ]; do
    case "$1" in
        --port)
            [ $# -ge 2 ] || { echo "Error: --port requires a value." >&2; exit 1; }
            PORT="$2"; shift 2 ;;
        --port=*) PORT="${1#--port=}"; shift ;;
        --no-check) CHECK=0; shift ;;
        -v | --verbose) VERBOSE=1; shift ;;
        -h | --help) sed -n '2,27p' "${BASH_SOURCE[0]}"; exit 0 ;;
        *) echo "Error: unknown argument '$1'. Try --help." >&2; exit 1 ;;
    esac
done

cd "$PACKAGE_ROOT"

# shellcheck source=scripts/anvil-lib.sh
source "$SCRIPT_DIR/anvil-lib.sh"

require_tools anvil cast forge

BLOBS="pkg/forge/src/_internal/LocalHostBytecode.sol"
[ -f "$BLOBS" ] || { echo "Error: $BLOBS missing. Run: npm run generate:local-host-bytecode" >&2; exit 1; }

RPC_URL="http://127.0.0.1:${PORT}"
# Its own out/, so a build here never becomes an input to `npm run build:templates`, which reads out/.
BUILD_OUT="internal/.deploy-config/out"

ANVIL_PID=""
trap cleanup EXIT INT TERM

echo "⛓  anvil on ${RPC_URL}"
load_generated_addresses_and_bootstrap
start_anvil

wait_for_node

echo ""
echo "🚀 deploying the pre-compiled blobs"
# No FOUNDRY_REMAPPINGS override: the blobs already carry the addresses, so pkg/src is compiled only for
# the one shared FheType enum the generated interfaces import, against the committed placeholder config.
# Without --verbose this step prints nothing for several seconds — forge's own output is captured, and a
# cold build cache adds a full solc pass over pkg/src. Say so, or it reads as a hang.
if [ "$VERBOSE" -eq 1 ]; then
    echo "   compiling and deploying (forge output below)"
else
    echo "   compiling and deploying — silent for a few seconds; pass -v to watch forge"
fi

DEPLOY_LOG="$(mktemp)"
# Captured rather than streamed: forge prints a compile log, a gas table and a transaction dump, which
# buries this script's own output. It is echoed in full on failure, or when --verbose asks for it.
if [ "$VERBOSE" -eq 1 ]; then
    if ! forge script pkg/forge/script/DeployLocalStack.s.sol:DeployLocalStack \
            --rpc-url "$RPC_URL" --out "$BUILD_OUT" --broadcast --slow 2>&1 | tee "$DEPLOY_LOG"; then
        rm -f "$DEPLOY_LOG"
        echo "Error: the deploy failed." >&2
        exit 1
    fi
elif ! forge script pkg/forge/script/DeployLocalStack.s.sol:DeployLocalStack \
        --rpc-url "$RPC_URL" --out "$BUILD_OUT" --broadcast --slow >"$DEPLOY_LOG" 2>&1; then
    cat "$DEPLOY_LOG" >&2
    rm -f "$DEPLOY_LOG"
    echo "Error: the deploy failed." >&2
    exit 1
fi

# `--slow` sends one transaction at a time and waits for each receipt, instead of firing all ~22 at once.
# Without it this stalls intermittently: anvil accepts the burst but stops mining part way through, and
# forge then waits on a receipt that never arrives (observed: nonce stuck at 24 of 26, two valid
# transactions sitting in the pending pool, both well under the 30M block gas limit, for minutes). The
# cast-based launchers never hit it because they already wait per transaction.
#
# `forge script` prints "ONCHAIN EXECUTION COMPLETE & SUCCESSFUL" even when the node dropped some of the
# transactions — it only warns. Treat that warning as the failure it is, or a half-deployed stack passes
# for a deployed one.
if grep -q "discarded by the RPC node" "$DEPLOY_LOG"; then
    rm -f "$DEPLOY_LOG"
    echo "Error: the node discarded some transactions — the stack is incomplete." >&2
    exit 1
fi
rm -f "$DEPLOY_LOG"

if [ "$CHECK" -eq 1 ]; then
    echo ""
    echo "🔎 checking the deployed stack"
    smoke_check || exit 1
fi

echo ""
report_stack

echo ""
enable_anvil_traces
echo "   anvil is still running on ${RPC_URL} — press Ctrl-C to stop."
wait "$ANVIL_PID"
