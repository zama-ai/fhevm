#!/usr/bin/env bash
#
# Start an anvil node and deploy the cleartext v13 stack onto it with NO Solidity compilation at all —
# only `cast` transactions carrying the pre-compiled blobs, plus two anvil RPCs. Ctrl-C stops the node.
#
# Usage: ./scripts/anvil-local-v2.sh [--port PORT] [--no-check] [-v|--verbose]
#
#   --port PORT       anvil port (default: 8545)
#   --no-check        skip the post-deploy smoke check
#   -v, --verbose     print every step (each contract as it is deployed)
#
# Four ways to get a local stack, fastest first:
#
#   anvil-fast.sh     anvil --init pkg/state/genesis.json      no deploy, no compile    (~1 s)
#   anvil-local-v2.sh cast-only replay of the deploy           no compile               (this script)
#   anvil-local.sh    forge script over the same blobs         one solc pass (~4 s)     (~8 s)
#   anvil.sh          compute addresses, compile pkg/src       full path                (~20 s)
#
# Requires only `anvil` and `cast`. No forge, no solc.
#
# ## Where the values come from
#
# Nothing is hardcoded that the package already states. Blobs are read out of
# pkg/forge/src/_internal/LocalHostBytecode.sol, addresses out of LocalHostAddresses.sol, and the whole
# bootstrap (signers, tx senders, IPs, storage URLs, thresholds, HCU limits, EIP-712 targets) out of
# LocalHostBootstrap.sol. All three are generated by `npm run generate:local-host-bytecode`, so this script
# cannot drift from them.
#
# The one thing it does restate is the *shape* of each initializer — the `cast calldata` format strings in
# INIT_SIGNATURES below. Values come from the generated files; signatures cannot, because bash has no way
# to read a Solidity ABI without a compiler. They are collected in one table so the duplication is in a
# single reviewable place. If an initializer's signature changes upstream, `ACLOwner.upgrade` reverts here
# rather than misbehaving — loud, but the diagnosis is worse than anvil-local.sh's compile error.
#
# ## Why PauserSet is the only anvil_setCode
#
# `anvil_setCode` writes runtime code. Of the fourteen blobs only PauserSet ships runtime (it has no
# constructor, so the generator classifies it that way); the rest ship creation code, which has to be run
# to produce anything. And the nine proxies need initialised storage — ERC-1967 slot, owner, signer arrays,
# EIP-712 domains — which setCode never touches, so those initializers have to actually execute.
#
# setCode also consumes no nonce, and PauserSet must occupy nonce 11 or ACLOwner takes it and lands on
# PauserSet's address. Hence the paired `anvil_setNonce`. That pairing works here but NOT inside a forge
# script: `forge script` derives CREATE addresses from its own simulation, which an RPC never reaches
# (measured: after anvil_setNonce to 5, vm.getNonce still read 1). With plain `cast` there is no
# simulation — every transaction reads the nonce back from the node — so it behaves as intended.
#
# ## Restriction
#
# Canonical stack only. The addresses are compiled into the blobs, so the deployer is fixed: the package
# mnemonic at account index 5, starting from nonce 0. For any other deployer use scripts/deploy.sh.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACKAGE_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

PORT=8545
CHECK=1
VERBOSE=0

parse_args() {
    while [ $# -gt 0 ]; do
        case "$1" in
            --port)
                [ $# -ge 2 ] || { echo "Error: --port requires a value." >&2; exit 1; }
                PORT="$2"; shift 2 ;;
            --port=*) PORT="${1#--port=}"; shift ;;
            --no-check) CHECK=0; shift ;;
            -v | --verbose) VERBOSE=1; shift ;;
            -h | --help) sed -n '2,21p' "${BASH_SOURCE[0]}"; exit 0 ;;
            *) echo "Error: unknown argument '$1'. Try --help." >&2; exit 1 ;;
        esac
    done
}

cd "$PACKAGE_ROOT"

# shellcheck source=scripts/anvil-lib.sh
source "$SCRIPT_DIR/anvil-lib.sh"

# Every address here is CREATE(deployer, nonce), so both the account and its starting nonce are
# preconditions rather than details — hence checking them before sending anything.
resolve_deployer() {
    PRIVATE_KEY="$(cast wallet private-key --mnemonic "$ANVIL_MNEMONIC" --mnemonic-index "$ACCOUNT_INDEX")"
    local derived actual_nonce
    derived="$(cast wallet address --private-key "$PRIVATE_KEY")"
    [ "$(printf '%s' "$derived" | tr 'A-Z' 'a-z')" = "$(printf '%s' "$DEPLOYER_ADDRESS" | tr 'A-Z' 'a-z')" ] || {
        echo "Error: derived deployer $derived != $DEPLOYER_ADDRESS from the generated addresses." >&2
        exit 1
    }
    actual_nonce="$(cast nonce "$DEPLOYER_ADDRESS" --rpc-url "$RPC_URL")"
    [ "$actual_nonce" = "$START_NONCE" ] || {
        echo "Error: deployer nonce is $actual_nonce, expected $START_NONCE. Every address derives from it." >&2
        exit 1
    }
    log "deployer $derived (mnemonic index $ACCOUNT_INDEX, nonce $actual_nonce)"
}

# ---------------------------------------------------------------------------
# Transaction helpers
# ---------------------------------------------------------------------------

expect_at() {
    local got="$1" want="$2" what="$3"
    [ "$(echo "$got" | tr 'A-Z' 'a-z')" = "$(echo "$want" | tr 'A-Z' 'a-z')" ] || {
        echo "Error: $what landed at $got, expected $want — the nonce sequence diverged." >&2; exit 1
    }
}

# An ERC-1967 proxy over `impl` with `initData`, constructor args appended to the shipped creation code.
create_proxy() {
    local impl="$1" init_data="$2" expected="$3" what="$4" args got
    args="$(cast abi-encode "constructor(address,bytes)" "$impl" "$init_data")"
    got="$(deploy_contract "$(read_blob ERC1967_PROXY_CREATION_CODE)${args#0x}" "$what")"
    expect_at "$got" "$expected" "$what"
    log "$what at $got (matches the compiled-in address)"
}

# Phase 1 — the nine empty proxies, nonces 0-10.
#
# Interleaved, and the order IS the address set: EmptyUUPSProxyACL at nonce 0, the ACL proxy at 1,
# EmptyUUPSProxy at 2, the remaining eight from 3. Deploying both empty implementations up front would
# shift every proxy by one and the ACL proxy would miss its canonical address.
deploy_empty_proxies() {
    deploy_empty_acl_implementation
    create_proxy "$EMPTY_ACL_IMPL" "$(cast calldata "$SIG_EMPTY_ACL_INIT" "$DEPLOYER_ADDRESS")" \
        "$ACL_ADDRESS" "ACL proxy"

    deploy_empty_implementation

    local init_empty
    init_empty="$(cast calldata "$SIG_EMPTY_INIT")"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$FHEVM_EXECUTOR_ADDRESS" "FHEVMExecutor proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$KMS_VERIFIER_ADDRESS" "KMSVerifier proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$INPUT_VERIFIER_ADDRESS" "InputVerifier proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$HCU_LIMIT_ADDRESS" "HCULimit proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$PROTOCOL_CONFIG_ADDRESS" "ProtocolConfig proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$KMS_GENERATION_ADDRESS" "KMSGeneration proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$CLEARTEXT_ARITHMETIC_ADDRESS" "CleartextArithmetic proxy"
    create_proxy "$EMPTY_IMPL" "$init_empty" "$CLEARTEXT_DB_ADDRESS" "CleartextDB proxy"
    echo "   ✅ 9 empty proxies at their canonical addresses"
}

# Phase 2 — PauserSet at nonce 11, the only anvil_setCode here.
#
# PauserSet is the sole blob shipped as runtime code (no constructor), so it is the only one setCode can
# place. setCode consumes no nonce, so PauserSet's nonce is skipped by hand — otherwise ACLOwner takes
# it and lands on
# PauserSet's own address. That pairing works with `cast` because there is no local simulation to desync;
# inside a forge script it silently would not.
install_pauser_set() {
    anvil_rpc anvil_setCode "$PAUSER_SET_ADDRESS" "0x$(read_blob PAUSER_SET_RUNTIME_CODE)"
    anvil_rpc anvil_setNonce "$DEPLOYER_ADDRESS" "$(printf '0x%x' $((START_NONCE + $(read_scalar ADDRESSED_NONCE_COUNT))))"
    local code
    code="$(cast code "$PAUSER_SET_ADDRESS" --rpc-url "$RPC_URL")"
    [ "${#code}" -gt 2 ] || { echo "Error: anvil_setCode left no code at PauserSet." >&2; exit 1; }
    echo "   ✅ PauserSet installed via anvil_setCode, nonce advanced to $(cast nonce "$DEPLOYER_ADDRESS" --rpc-url "$RPC_URL")"
}

# Phase 3 — ACLOwner at nonce 12, then ownership moves to it two-step.
#
# addPauser is onlyACLOwner, so it has to happen while the deployer still owns ACL.
setup_acl_owner() {
    deploy_acl_owner
    send_tx "$PAUSER_SET_ADDRESS" "addPauser(address)" "$ACL_OWNER"
    send_tx "$ACL_ADDRESS" "transferOwnership(address)" "$ACL_OWNER"
    send_tx "$ACL_OWNER" "acceptACLOwnership()"
    echo "   ✅ ACLOwner $ACL_OWNER owns ACL"
}

# Phase 4 — the nine real implementations. Deployed AFTER the proxies on purpose: from nonce 0 they would
# land on canonical addresses.
deploy_implementations() {
    deploy_real_implementations
    echo "   ✅ 9 implementations deployed"
}

main() {
    parse_args "$@"

    require_tools anvil cast

    require_generated_files "$BYTECODE_SOL" "$ADDRESSES_SOL" "$BOOTSTRAP_SOL"

    # ---------------------------------------------------------------------------
    # Readers for the three generated files
    # ---------------------------------------------------------------------------

    # A scalar `... constant NAME = VALUE;` in LocalHostBootstrap.

    load_generated_addresses_and_bootstrap

    RPC_URL="http://127.0.0.1:${PORT}"
    export ETH_RPC_URL="$RPC_URL"

    ANVIL_PID=""
    trap cleanup EXIT INT TERM

    echo "⛓  anvil on ${RPC_URL}"
    # `--silent` starts anvil with its logger disabled, not merely without the banner: anvil's lib.rs does
    # `logger.set_enabled(!config.silent)`, and anvil_setLoggingEnabled flips that same flag. So this script's
    # ~25 cast calls stay quiet and traces can be switched back on for the interactive session afterwards.
    # It has no bearing on the anvil_setCode/anvil_setNonce steering below — that is RPC behaviour, not logging.
    start_anvil
    wait_for_node
    resolve_deployer

    echo ""
    echo "🚀 deploying from the pre-compiled blobs (cast only, no solc)"
    deploy_empty_proxies
    install_pauser_set
    setup_acl_owner
    deploy_implementations
    build_initializer_calldata
    upgrade_stack_atomically

    if [ "$CHECK" -eq 1 ]; then
        echo ""
        echo "🔎 checking the deployed stack"
        smoke_check || exit 1
    fi

    echo ""
    report_stack

    echo ""
    enable_anvil_traces
    echo "   anvil is still running on ${RPC_URL} — press Ctrl-C to stop."
    wait "$ANVIL_PID"
}

main "$@"
