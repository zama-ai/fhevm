// The `host-contracts-cleartext` LAYOUT, applied to the workspace-wide rules in sdk/eslint.base.mjs.
//
// Two files, two jobs, and the split is the same one `foundry.base.toml` draws:
//
//   sdk/eslint.base.mjs                    POLICY — which rules, at what severity. No paths.
//   sdk/host-contracts-cleartext/…         LAYOUT — which directories those rules apply to. This file.
//   <gen>/eslint.config.js                 that generation's own `ignores`, naming its own test files.
//
// It sits beside RULES.md rather than inside a generation because every generation has the SAME
// layout — `v12/eslint.config.base.js` and `v13/eslint.config.base.js` were byte-identical before
// this split. Under rule 22 a change to v13 must be ported to v12 in the same change, so two
// identical copies were two chances to forget; one file removes the obligation instead of restating
// it. A new generation gets the layout by importing this, and only declares what is genuinely its
// own.
//
// It is `.mjs` for the same reason the base is: the nearest package.json is `sdk/package.json`,
// which deliberately declares no `type`, so a `.js` here would load as ESM only via Node's syntax
// detection — with a MODULE_TYPELESS_PACKAGE_JSON warning on every load whose suggested fix is the
// one change this workspace must not make.
import eslintBase from '../eslint.base.mjs';

// Published payload: browser-safe, explicit return types, type-aware rules.
const publicFiles = ['pkg/ts/**/*.ts'];

// Node-side tooling and tests: same rules, node globals allowed.
//
// `create2-deploy` is node-side tooling like `internal/`, and was absent from this list until it was
// noticed that ~2400 lines were linted by nothing at all — an unused import survived a full typecheck
// AND a full lint run. Its own tsconfig extends the same base, so the type-aware rules work the same
// way. It is also the clearest example of why this list is not in `eslint.base.mjs`: no other
// package in the workspace has such a directory.
const nodeFiles = ['internal/**/*.ts', 'test/**/*.ts', 'create2-deploy/**/*.ts'];

// TypeScript emit, regenerated by build:cjs / build:esm / build:types.
const generatedFiles = ['pkg/ts/_cjs/**', 'pkg/ts/_esm/**', 'pkg/ts/_types/**'];

/**
 * The shared rule set, scoped to the cleartext generation layout.
 *
 * @param {string}   packageDir  Always `import.meta.dirname` from the generation's own config — it
 *                               becomes `tsconfigRootDir`, so it must be that generation's root and
 *                               not the workspace root.
 * @param {string[]} [ignores]   Extra per-generation exclusions, on top of the layout ones below.
 * @returns {import('typescript-eslint').ConfigArray}
 */
export default function eslintCleartext(packageDir, ignores = []) {
  return eslintBase({
    packageDir,
    publicFiles,
    nodeFiles,
    // `internal/` is held to the published code's standard here: it generates the payload, so a
    // sloppy signature there produces a sloppy artifact.
    returnTypeFiles: [...publicFiles, 'internal/**/*.ts'],
    ignores: [
      ...generatedFiles,
      'cache/**',
      'out/**',
      'tarball/**',
      // The e2e test imports a second package (@fhevm/host-contracts-cleartext-v12) that only exists
      // after `test:upgrade-e2e` installs it. It's excluded from every tsconfig so the fixture-less
      // `tsc` runs don't fail, so the eslint project service can't type it — skip it here. Its own
      // typecheck runs against test/ts/tsconfig.e2e.json inside `test:upgrade-e2e`.
      //
      // Inert in the oldest generation, which has no upgrade e2e to ignore. Kept shared
      // anyway, per rule 22: ignoring a file that does not exist costs nothing, and the entry is
      // already correct the day that generation stops being the floor.
      'test/ts/upgrade-e2e.test.ts',
      ...ignores,
    ],
  });
}
