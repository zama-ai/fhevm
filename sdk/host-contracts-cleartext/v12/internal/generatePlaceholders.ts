// Generates internal/placeholders/addresses.sol.
//
// Must run BEFORE `forge build` — solc compiles this file's literals into the bytecode, so writing it
// afterwards leaves the previous run's markers baked in at the offsets generateTemplates.ts records.
//
// These addresses are markers, never deployed: solc compiles them in as literals, generateTemplates.ts
// records where they land, and the TS deploy overwrites them (pkg/ts/utils.ts asserts none survives).
// So a marker's only requirement is to be findable and unique.
//
// Derived as keccak256("fhevm.placeholder.<NAME>")[0:20] instead of chosen by hand, because
// hand-picked digit runs (0x1011121314…) carry structure that can overlap: the previous PAUSER_SET
// marker shared an ascending byte run with ACL's, so one long ascending sequence in bytecode could
// match both and patching would clobber one with the other. keccak output has no such structure.
//
// Markers contain letters, so Solidity demands EIP-55 checksums (it only skips the check for
// digit-only literals, which is what the old markers relied on) — getAddress supplies them.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getAddress, keccak256, toHex } from 'viem';
import { ADDRESS_NAMES } from './constants.ts';

////////////////////////////////////////////////////////////////////////////////

const DERIVATION_PREFIX = 'fhevm.placeholder.';
const PLACEHOLDERS_PATH = join(dirname(fileURLToPath(import.meta.url)), 'placeholders', 'addresses.sol');

////////////////////////////////////////////////////////////////////////////////

function _render(): string {
  const lines = ADDRESS_NAMES.map((name) => `address constant ${name} = address(${placeholderFor(name)});`);
  return `// SPDX-License-Identifier: BSD-3-Clause-Clear
pragma solidity ^0.8.24;

// GENERATED by internal/generatePlaceholders.ts - do not edit by hand.
// Markers only: every value is patched out at deploy time and none is ever deployed.
// Derived as keccak256("${DERIVATION_PREFIX}<NAME>")[0:20]; see the generator for why.
${lines.join('\n')}
`;
}

////////////////////////////////////////////////////////////////////////////////

/**
 * Writes the marker file. The only thing here that touches disk, and it is never reached by importing
 * The module — templates.test.ts imports `derivePlaceholder` and cannot rewrite the file by doing so.
 */
export function writePlaceholders(): void {
  writeFileSync(PLACEHOLDERS_PATH, _render(), 'utf8');
}

////////////////////////////////////////////////////////////////////////////////

/** keccak256(seed)[0:20], EIP-55 checksummed. Exposed so tests can derive independent marker sets. */
export function derivePlaceholder(seed: string): `0x${string}` {
  return getAddress(`0x${keccak256(toHex(seed)).slice(2, 42)}`);
}

////////////////////////////////////////////////////////////////////////////////

export function placeholderFor(name: string): `0x${string}` {
  return derivePlaceholder(`${DERIVATION_PREFIX}${name}`);
}
