// Emits the expected `getVersion()` table for both toolchains, from the scan in @fhevm/sdk-common-dev.
//
// Two outputs because two toolchains consume it and neither can read the other's:
//   - pkg/forge/src/_internal/LocalHostVersions.sol  — the forge verify script and the forge test
//   - pkg/ts/artifacts/versions.ts                   — the TS deploy test
//
// Both are generated from one scan, so a bumped contract cannot leave one of them stale — which is what
// The three hand-maintained copies these replace could not promise.

import { readContractVersions, solidityConstantName, tsKeyName, type ContractVersion } from '@fhevm/sdk-common-dev';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PACKAGE_ROOT_ABS_PATH, PKG_DIR_ABS_PATH } from './constants.ts';

////////////////////////////////////////////////////////////////////////////////

export const SOLIDITY_OUTPUT_PATH = join(PKG_DIR_ABS_PATH, 'forge', 'src', '_internal', 'LocalHostVersions.sol');

// Deliberately NOT under ts/artifacts/: generateTemplates.ts owns that directory and starts by
// `rmSync`-ing it, so anything another generator writes there is deleted on the next build. Sits beside
// ts/cleartext-config.ts instead, the existing precedent for a generated module in ts/.
export const TS_OUTPUT_PATH = join(PKG_DIR_ABS_PATH, 'ts', 'versions.ts');

const HEADER = `// AUTOGENERATED by \`npm run generate:contract-versions\`.
// DO NOT EDIT — your changes will be overwritten. See internal/generateContractVersions.ts.
//
// The string each contract's \`getVersion()\` returns, read from the CONTRACT_NAME + MAJOR/MINOR/PATCH
// constants in the source that declares it. Note the cleartext variants inherit \`getVersion\` and so
// report their BASE contract's name -- CleartextFHEVMExecutor identifies itself as FHEVMExecutor.
// CleartextDB is absent because it exposes no \`getVersion\` at all.`;

////////////////////////////////////////////////////////////////////////////////

function _renderSolidity(versions: readonly ContractVersion[]): string {
  const constants = versions
    .map(
      (entry) =>
        `    /// @dev ${entry.sourcePath}\n` +
        `    string internal constant ${solidityConstantName(entry.reportedName)} = "${entry.version}";`,
    )
    .join('\n\n');

  return `// SPDX-License-Identifier: BSD-3-Clause-Clear
pragma solidity ^0.8.24;

${HEADER}

library LocalHostVersions {
${constants}
}
`;
}

////////////////////////////////////////////////////////////////////////////////

function _renderTypeScript(versions: readonly ContractVersion[]): string {
  const entries = versions.map((entry) => `  ${tsKeyName(entry.reportedName)}: '${entry.version}',`).join('\n');

  return `${HEADER}

export const CONTRACT_VERSIONS = {
${entries}
} as const;
`;
}

////////////////////////////////////////////////////////////////////////////////

export function generateContractVersions(): void {
  // Scanned under pkg/src, with paths reported from pkg/ so the provenance comments read `src/...`.
  const versions = readContractVersions(join(PKG_DIR_ABS_PATH, 'src'), PKG_DIR_ABS_PATH);

  writeFileSync(SOLIDITY_OUTPUT_PATH, _renderSolidity(versions), 'utf8');
  writeFileSync(TS_OUTPUT_PATH, _renderTypeScript(versions), 'utf8');

  console.log(`Wrote ${String(versions.length)} contract versions:`);
  for (const entry of versions) {
    console.log(`  ${entry.version.padEnd(32)} ${entry.sourcePath}`);
  }
  console.log(`  -> ${SOLIDITY_OUTPUT_PATH.slice(PACKAGE_ROOT_ABS_PATH.length + 1)}`);
  console.log(`  -> ${TS_OUTPUT_PATH.slice(PACKAGE_ROOT_ABS_PATH.length + 1)}`);
}
